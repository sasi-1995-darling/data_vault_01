---- LOGIC LAYER ----

, LOGIC_FPR as (
    SELECT
        PO_HEADER_ID
      , PO_LINE_NUMBER
      , TRANSACTION_ID
      , MATERIAL_DOCUMENT_NUMBER
      , MATERIAL_DOCUMENT_ITEM
      , PO_RECEIPT_QUANTITY
      , PO_RECEIPT_PRICE
      , PO_RECEIPT_VALUE_LOCAL
      , PO_RECEIPT_VALUE
      , PLANT_HK
      , ITEM_HK
      , LEGAL_ENTITY_HK
      , PO_HEADER_HK
      , PO_LINE_RECEIPT_IND_HK
      , PO_RECEIPT_DATE__YYYYMMDD
      , SUPPLIER_HK
    FROM SRC_FPR
)

, LOGIC_DPH as (
    SELECT
        PO_NUMBER
      , PO_DOCUMENT_TYPE
      , PO_HEADER_DEL_IND
      , PO_PROCESSING_STATUS
      , PO_PAYMENT_TERMS
      , INCOTERMS_1
      , INCOTERMS_2
      , PURCHASING_ORG
      , BUYER_PLANNER_CODE
      , PO_CURRENCY
      , REC_SRC
      , PO_HEADER_HK                                                 as                                   DPH_PO_HEADER_HK
    FROM SRC_DPH
)

, LOGIC_PLRI as (
    SELECT
        PO_RECEIPT_TYPE
      , PO_RECEIPT_UOM
      , MOVEMENT_TYPE
      , DEBIT_CREDIT_IND
      , LOCAL_CURRENCY
      , PO_LINE_RECEIPT_IND_HK                                       as                        PLRI_PO_LINE_RECEIPT_IND_HK
    FROM SRC_PLRI
)

, LOGIC_FPI_PLRI as (
    SELECT
        PO_LINE_DEL_IND
      , GOODS_RECEIPT_IND
      , GOODS_RECEIPT_COMPLETE_IND
      , CLOSED_STATUS
      , INVOICE_RECEIPT_IND
      , ACCOUNT_ASSIGNMENT
      , ORDER_UOM
      , PURCHASE_ORDER_PRICE_UOM
      , PO_LINE_RECEIPT_IND_HK                                       as                    FPI_PLRI_PO_LINE_RECEIPT_IND_HK
    FROM SRC_FPI_PLRI
)

, LOGIC_DS as (
    SELECT
        SUPPLIER_BK                                                  as                                        SUPPLIER_ID
      , SUPPLIER_NAME_1                                              as                                      SUPPLIER_NAME
      , SUPPLIER_HK                                                  as                                     DS_SUPPLIER_HK
    FROM SRC_DS
)

, LOGIC_FPI as (
    SELECT
        ORDER_QUANTITY
      , NET_PRICE
      , PRICE_UNIT
      , NET_VALUE
      , GROSS_VALUE
      , TOTAL_PLANNED_LEAD_DAYS
      , GOODS_RECEIPT_PROCESSING_DAYS
      , CONVERSION_PRICE_UOM_TO_ORDER_UOM_N
      , CONVERSION_PRICE_UOM_TO_ORDER_UOM_D
      , PO_HEADER_ID                                                 as                                   FPI_PO_HEADER_ID
      , PO_LINE_NUMBER                                               as                                 FPI_PO_LINE_NUMBER
      , PO_LINE_RECEIPT_IND_HK                                       as                         FPI_PO_LINE_RECEIPT_IND_HK
      , PO_CREATION_DATE__YYYYMMDD
    FROM SRC_FPI
)

, LOGIC_DFY as (
    SELECT
        DATE                                                         as                                    PO_RECEIPT_DATE
      , FISCAL_445_CAL_MONTH                                         as                            PO_RECEIPT_FISCAL_MONTH
      , DATE_BK
    FROM SRC_DFY
)

, LOGIC_FPI_DFY as (
    SELECT
        DATE                                                         as                                   PO_CREATION_DATE
      , FISCAL_445_CAL_MONTH                                         as                           PO_CREATION_FISCAL_MONTH
      , DATE_BK                                                      as                                    FPI_DFY_DATE_BK
    FROM SRC_FPI_DFY
)

, LOGIC_DI as (
    SELECT
        ITEM_NUMBER
      , BASE_MATERIAL
      , ITEM_CATEGORY
      , ITEM_ID
    FROM SRC_DI
)

, LOGIC_DLE as (
    SELECT
        LEGAL_ENTITY_CODE
      , LEGAL_ENTITY_NAME
      , LEGAL_ENTITY_REGION
      , LEGAL_ENTITY_HK                                              as                                DLE_LEGAL_ENTITY_HK
    FROM SRC_DLE
)
