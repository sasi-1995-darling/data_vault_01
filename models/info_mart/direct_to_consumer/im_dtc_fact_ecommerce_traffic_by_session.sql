SRC_fact_traffic   as ( SELECT BKCC, ECOMMERCE_ACCOUNT_BK, ECOMMERCE_ACCOUNT_COUNTRY, ECOMMERCE_ACCOUNT_HK, ECOMMERCE_ANALYTICS_SERVICE, 
