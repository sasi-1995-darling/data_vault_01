                        ECOMMERCE_PROPERTY_TYPE, ENGAGED_SESSIONS, ENGAGEMENT_RATE, EVENTS_PER_ENGAGED_SESSION, EVENTS_PER_SESSION, EVENT_COUNT, KEY_EVENTS, 
                        REC_SRC, SESSIONS, SESSIONS_PER_USER, SESSION_CHANNEL_GROUP, SESSION_DATE__YYYYMMDD, TOTAL_REVENUE, TOTAL_USERS, WEEK_ENDING_DATEKEY 
                        FROM {{ ref('fact_ecommerce_traffic_by_session') }} as SRC  )

