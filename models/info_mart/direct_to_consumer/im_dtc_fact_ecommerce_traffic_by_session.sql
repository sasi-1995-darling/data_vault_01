        , SESSIONS
        , ENGAGEMENT_RATE
        , KEY_EVENTS
        , TOTAL_USERS
        , ENGAGED_SESSIONS
        , EVENT_COUNT
        , EVENTS_PER_SESSION
        , EVENTS_PER_ENGAGED_SESSION
        , SESSIONS_PER_USER
        , TOTAL_REVENUE
