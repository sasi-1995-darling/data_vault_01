---- SRC LAYER ----
WITH
SRC_DDS            as ( SELECT ACCOUNT_ID, BKCC, CANCELLATION_REASON, DEVICE_ACCOUNT_BK, DEVICE_LOCATION_BK, FIVETRAN_DELETED, FIVETRAN_SYNCED, IS_ACTIVE, PLAN_ID, PROVIDER_CUSTOMER_ID, PROVIDER_SUBSCRIPTION_ID, REC_SRC, RELATED_ENTITY, RELATED_ENTITY_ID, SOURCE_ID, STRIPE_PROVIDER_DATA, SUBSCRIPTION_PROVIDER FROM {{ ref('dim_device_account_location_subscription') }} as SRC  )

/*
SRC_DDS            as ( SELECT * FROM BUS_VAULT.DIM_DEVICE_ACCOUNT_LOCATION_SUBSCRIPTION )
*/
---- LOGIC LAYER ----

, LOGIC_DDS as (
    SELECT
        DEVICE_ACCOUNT_BK
      , DEVICE_LOCATION_BK
      , BKCC
      , REC_SRC
      , ACCOUNT_ID
      , FIVETRAN_SYNCED
      , RELATED_ENTITY_ID
      , IS_ACTIVE
      , PROVIDER_CUSTOMER_ID
      , SOURCE_ID
      , SUBSCRIPTION_PROVIDER
      , PROVIDER_SUBSCRIPTION_ID
      , STRIPE_PROVIDER_DATA
      , PLAN_ID
      , RELATED_ENTITY
      , FIVETRAN_DELETED
      , CANCELLATION_REASON
    FROM SRC_DDS
)
---- RENAME LAYER ----

, RENAME_DDS as (
    SELECT
        DEVICE_ACCOUNT_BK
      , DEVICE_LOCATION_BK
      , BKCC
      , REC_SRC
      , ACCOUNT_ID
      , FIVETRAN_SYNCED
      , RELATED_ENTITY_ID
      , IS_ACTIVE
      , PROVIDER_CUSTOMER_ID
      , SOURCE_ID
      , SUBSCRIPTION_PROVIDER
      , PROVIDER_SUBSCRIPTION_ID
      , STRIPE_PROVIDER_DATA
      , PLAN_ID
      , RELATED_ENTITY
      , FIVETRAN_DELETED
      , CANCELLATION_REASON
    FROM LOGIC_DDS
)
---- FILTER LAYER ----

, FILTER_DDS as (
    SELECT *
    FROM RENAME_DDS
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_DDS
)

---- FINAL LAYER ----
SELECT
          DEVICE_ACCOUNT_BK
        , DEVICE_LOCATION_BK
        , BKCC
        , REC_SRC
        , ACCOUNT_ID
        , FIVETRAN_SYNCED
        , RELATED_ENTITY_ID
        , IS_ACTIVE
        , PROVIDER_CUSTOMER_ID
        , SOURCE_ID
        , SUBSCRIPTION_PROVIDER
        , PROVIDER_SUBSCRIPTION_ID
        , STRIPE_PROVIDER_DATA
        , PLAN_ID
        , RELATED_ENTITY
        , FIVETRAN_DELETED
        , CANCELLATION_REASON
FROM JOIN_RESULT
