---- RENAME LAYER ----

, RENAME_DDG as (
    SELECT
        DATE_BK
      , DATE_ACTUAL
      , DAY_NAME
      , MONTH_ACTUAL
      , YEAR_ACTUAL
      , QUARTER_ACTUAL
      , DAY_OF_WEEK
      , FIRST_DAY_OF_WEEK
      , WEEK_OF_YEAR
      , DAY_OF_MONTH
      , DAY_OF_QUARTER
      , DAY_OF_YEAR
