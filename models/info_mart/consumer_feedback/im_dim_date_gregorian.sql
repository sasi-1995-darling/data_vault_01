      , LAST_DAY_OF_YEAR
      , FIRST_DAY_OF_QUARTER
      , LAST_DAY_OF_QUARTER
      , LAST_DAY_OF_WEEK
      , QUARTER_NAME
      , HOLIDAY_DESC
      , IS_HOLIDAY
      , SNAPSHOT_DATE_FPA
      , SNAPSHOT_DATE_BILLINGS
      , DAYS_IN_MONTH_COUNT
      , DAYS_UNTIL_LAST_DAY_OF_MONTH
      , CURRENT_DATE_ACTUAL
      , CURRENT_FIRST_DAY_OF_MONTH
      , CURRENT_DAY_OF_MONTH
    FROM LOGIC_DDG
)
---- FILTER LAYER ----

, FILTER_DDG as (
    SELECT *
    FROM RENAME_DDG
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_DDG
)

