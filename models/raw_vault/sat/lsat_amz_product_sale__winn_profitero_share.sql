, FILTER_STG as (
    SELECT *
    FROM RENAME_STG
)
---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT * FROM FILTER_STG
)

---- FINAL LAYER ----
SELECT
          ASIN_SNS_CATEGORY_HK
        , DATE
        , DIM_AMZ_PRODUCT_SALE_KEY
        , DIM_DATE_KEY
        , DIM_AMZ_PRODUCT_KEY
