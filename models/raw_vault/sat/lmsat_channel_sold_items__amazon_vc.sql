---- RENAME LAYER ----

, RENAME_s as (
    SELECT
        REPORT_START_DT
      , REPORT_END_DT
      , ASIN
      , CUSTOMER_RETURNS
      , ORDERDED_REVENUE_AMT
      , ORDERDED_REV_CURRCODE
