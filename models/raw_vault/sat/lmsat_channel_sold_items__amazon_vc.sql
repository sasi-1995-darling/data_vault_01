      , HASHDIFF
      , MODEL_STYLE_NUMBER
      , MODEL_NUMBER
    FROM LOGIC_s
)
---- FILTER LAYER ----

, FILTER_s as (
    SELECT *
    FROM RENAME_s
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_s
)

---- FINAL LAYER ----
SELECT
          REPORT_START_DT
        , REPORT_END_DT
        , ASIN
        , CUSTOMER_RETURNS
        , ORDERDED_REVENUE_AMT
        , ORDERDED_REV_CURRCODE
