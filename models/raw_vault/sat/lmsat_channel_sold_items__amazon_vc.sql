        , LOAD_DTS
        , REC_SRC
        , CHANNEL_SOLD_ITEM_LHK
        , HASHDIFF
        , MODEL_STYLE_NUMBER
        , MODEL_NUMBER
FROM JOIN_RESULT
{% if is_incremental() %}
WHERE NOT EXISTS (
SELECT 1 
