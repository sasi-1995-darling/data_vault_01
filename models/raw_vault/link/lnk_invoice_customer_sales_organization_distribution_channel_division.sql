---- SRC LAYER ----
WITH
SRC_HOFRSALES      as ( SELECT CUSTOMER_HK, DISTRIBUTION_CHANNEL_HK, DIVISION_HK, INVOICE_HK, ITEM_HK, LNK_INVOICE_CUSTOMER_SALES_ORGANIZATION_DISTRIBUTION_CHANNEL_DIVISION_ITEM_HK, LOAD_DTS, REC_SRC, SALES_ORGANIZATION_HK, UNIQUE_KEY FROM {{ ref('v_psa_stg_legacy_hofrus_sales__hofr_ecl') }} as SRC 
                        QUALIFY ROW_NUMBER() OVER(PARTITION BY LNK_INVOICE_CUSTOMER_SALES_ORGANIZATION_DISTRIBUTION_CHANNEL_DIVISION_ITEM_HK ORDER BY LOAD_DTS )=1 )

/*
SRC_HOFRSALES      as ( SELECT * FROM STAGING.v_psa_stg_legacy_hofrus_sales__hofr_ecl )
*/
---- LOGIC LAYER ----

, LOGIC_HOFRSALES as (
    SELECT
        LNK_INVOICE_CUSTOMER_SALES_ORGANIZATION_DISTRIBUTION_CHANNEL_DIVISION_ITEM_HK
      , INVOICE_HK
      , CUSTOMER_HK
      , SALES_ORGANIZATION_HK
      , DISTRIBUTION_CHANNEL_HK
      , DIVISION_HK
      , ITEM_HK
      , UNIQUE_KEY
      , LOAD_DTS
      , REC_SRC
    FROM SRC_HOFRSALES
)
---- RENAME LAYER ----

, RENAME_HOFRSALES as (
    SELECT
        LNK_INVOICE_CUSTOMER_SALES_ORGANIZATION_DISTRIBUTION_CHANNEL_DIVISION_ITEM_HK
      , INVOICE_HK
      , CUSTOMER_HK
      , SALES_ORGANIZATION_HK
      , DISTRIBUTION_CHANNEL_HK
      , DIVISION_HK
      , ITEM_HK
      , UNIQUE_KEY
      , LOAD_DTS
      , REC_SRC
    FROM LOGIC_HOFRSALES
)
---- FILTER LAYER ----

, FILTER_HOFRSALES as (
    SELECT *
    FROM RENAME_HOFRSALES
)
---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT * FROM FILTER_HOFRSALES
)

---- FINAL LAYER ----
SELECT
          LNK_INVOICE_CUSTOMER_SALES_ORGANIZATION_DISTRIBUTION_CHANNEL_DIVISION_ITEM_HK
        , INVOICE_HK
        , CUSTOMER_HK
        , SALES_ORGANIZATION_HK
        , DISTRIBUTION_CHANNEL_HK
        , DIVISION_HK
        , ITEM_HK
        , UNIQUE_KEY
        , LOAD_DTS
        , REC_SRC
FROM JOIN_RESULT
{% if is_incremental() %}
WHERE NOT EXISTS (
    SELECT 1 
    FROM {{ this }} existing
    WHERE existing.LNK_INVOICE_CUSTOMER_SALES_ORGANIZATION_DISTRIBUTION_CHANNEL_DIVISION_ITEM_HK = JOIN_RESULT.LNK_INVOICE_CUSTOMER_SALES_ORGANIZATION_DISTRIBUTION_CHANNEL_DIVISION_ITEM_HK
)
{% endif %}
{% if not is_incremental() %}

union all
SELECT 
MD5_BINARY(GR.VALUE) AS LNK_INVOICE_CUSTOMER_SALES_ORGANIZATION_DISTRIBUTION_CHANNEL_DIVISION_ITEM_HK,
MD5_BINARY(GR.VALUE) AS INVOICE_HK,
MD5_BINARY(GR.VALUE) AS CUSTOMER_HK,
MD5_BINARY(GR.VALUE) AS SALES_ORGANIZATION_HK,
MD5_BINARY(GR.VALUE) AS DISTRIBUTION_CHANNEL_HK,
MD5_BINARY(GR.VALUE) AS DIVISION_HK,
MD5_BINARY(GR.VALUE) AS ITEM_HK,
GR.VALUE::number AS UNIQUE_KEY,
CONVERT_TIMEZONE('UTC','1900-01-01'::TIMESTAMP) AS LOAD_DTS,
'USAZET.SNOWFLAKE.FBIN.DERIVED' AS REC_SRC
FROM
TABLE(strtok_split_to_table('0|-1|-2', '|')) AS GR
{% endif %}
