---- SRC LAYER ----
WITH
SRC_a              as ( SELECT LNK_GOODS_MOVEMENT_HK, GOODS_MOVEMENT_ITEM_DOCUMENT_HK, PLANT_HK, GOODS_STORAGE_LOCATION_HK, SUPPLIER_HK, CUSTOMER_HK, UOM_HK, ORDER_LINE_HK, CUSTOMER_SHIP_LOCATION_HK, PO_ITEM_HK, PRODUCTION_ORDER_HK, ITEM_HK, DELIVERY_LINE_HK, LOAD_DTS, REC_SRC FROM {{ ref('v_psa_stg_goods_movement__winn_sap') }} as SRC 
                        QUALIFY (ROW_NUMBER() OVER(PARTITION BY LNK_GOODS_MOVEMENT_HK ORDER BY LOAD_DTS ))=1 )

/*
SRC_a              as ( SELECT * FROM STAGING.V_PSA_STG_INVENTORY_MOVEMENT__WINN_SAP )
*/
---- LOGIC LAYER ----

, LOGIC_a as (
    SELECT
        LNK_GOODS_MOVEMENT_HK
      , GOODS_MOVEMENT_ITEM_DOCUMENT_HK
      , PLANT_HK
      , GOODS_STORAGE_LOCATION_HK
      , SUPPLIER_HK
      , CUSTOMER_HK
      , UOM_HK
      , ORDER_LINE_HK
      , CUSTOMER_SHIP_LOCATION_HK
      , PO_ITEM_HK
      , PRODUCTION_ORDER_HK
      , ITEM_HK
      , DELIVERY_LINE_HK
      , LOAD_DTS
      , REC_SRC
    FROM SRC_a
)
---- RENAME LAYER ----

, RENAME_a as (
    SELECT
        LNK_GOODS_MOVEMENT_HK
      , GOODS_MOVEMENT_ITEM_DOCUMENT_HK
      , PLANT_HK
      , GOODS_STORAGE_LOCATION_HK
      , SUPPLIER_HK
      , CUSTOMER_HK
      , UOM_HK
      , ORDER_LINE_HK
      , CUSTOMER_SHIP_LOCATION_HK
      , PO_ITEM_HK
      , PRODUCTION_ORDER_HK
      , ITEM_HK
      , DELIVERY_LINE_HK
      , LOAD_DTS
      , REC_SRC
    FROM LOGIC_a
)
---- FILTER LAYER ----

, FILTER_a as (
    SELECT *
    FROM RENAME_a
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_a
)

---- FINAL LAYER ----
SELECT
          LNK_GOODS_MOVEMENT_HK
        , GOODS_MOVEMENT_ITEM_DOCUMENT_HK
        , PLANT_HK
        , GOODS_STORAGE_LOCATION_HK
        , SUPPLIER_HK
        , CUSTOMER_HK
        , UOM_HK
        , ORDER_LINE_HK
        , CUSTOMER_SHIP_LOCATION_HK
        , PO_ITEM_HK
        , PRODUCTION_ORDER_HK
        , ITEM_HK
        , DELIVERY_LINE_HK
        , LOAD_DTS
        , REC_SRC
FROM JOIN_RESULT
{% if is_incremental() %}
WHERE NOT EXISTS (
    SELECT 1 
    FROM {{ this }} existing
    WHERE existing.LNK_GOODS_MOVEMENT_HK = JOIN_RESULT.LNK_GOODS_MOVEMENT_HK
)
{% endif %}
