---- SRC LAYER ----
WITH
SRC_LIPS           as ( SELECT COST_CENTER_HK, DELIVERY_HK, DELIVERY_LINE_DETAIL_LHK, DELIVERY_LINE_HK, DISTRIBUTION_CHANNEL_HK, DIVISION_HK, 
                        GOODS_STORAGE_LOCATION_HK, ITEM_HK, LOAD_DTS, ORDER_HEADER_HK, ORDER_LINE_HK, PLANT_HK, REC_SRC 
                        FROM {{ ref('v_psa_stg_delivery_line_detail__winn_sap') }} as SRC 
                        QUALIFY ROW_NUMBER() OVER(PARTITION BY DELIVERY_LINE_DETAIL_LHK ORDER BY LOAD_DTS )=1 )

/*
SRC_LIPS           as ( SELECT * FROM STAGING.v_psa_stg_delivery_line_detail__winn_sap )
*/
---- LOGIC LAYER ----

, LOGIC_LIPS as (
    SELECT
        DELIVERY_LINE_DETAIL_LHK
      , DELIVERY_HK
      , DELIVERY_LINE_HK
      , ITEM_HK
      , ORDER_HEADER_HK
      , ORDER_LINE_HK
      , PLANT_HK
      , GOODS_STORAGE_LOCATION_HK
      , DISTRIBUTION_CHANNEL_HK
      , DIVISION_HK
      , COST_CENTER_HK
      , LOAD_DTS
      , REC_SRC
    FROM SRC_LIPS
)
---- RENAME LAYER ----

, RENAME_LIPS as (
    SELECT
        DELIVERY_LINE_DETAIL_LHK
      , DELIVERY_HK
      , DELIVERY_LINE_HK
      , ITEM_HK
      , ORDER_HEADER_HK
      , ORDER_LINE_HK
      , PLANT_HK
      , GOODS_STORAGE_LOCATION_HK
      , DISTRIBUTION_CHANNEL_HK
      , DIVISION_HK
      , COST_CENTER_HK
      , LOAD_DTS
      , REC_SRC
    FROM LOGIC_LIPS
)
---- FILTER LAYER ----

, FILTER_LIPS as (
    SELECT *
    FROM RENAME_LIPS
)
---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT * FROM FILTER_LIPS
)

---- FINAL LAYER ----
SELECT
          DELIVERY_LINE_DETAIL_LHK
        , DELIVERY_HK
        , DELIVERY_LINE_HK
        , ITEM_HK
        , ORDER_HEADER_HK
        , ORDER_LINE_HK
        , PLANT_HK
        , GOODS_STORAGE_LOCATION_HK
        , DISTRIBUTION_CHANNEL_HK
        , DIVISION_HK
        , COST_CENTER_HK
        , LOAD_DTS
        , REC_SRC
FROM JOIN_RESULT
{% if is_incremental() %}
WHERE NOT EXISTS (
    SELECT 1 
    FROM {{ this }} existing
    WHERE existing.DELIVERY_LINE_DETAIL_LHK = JOIN_RESULT.DELIVERY_LINE_DETAIL_LHK
)
{% endif %}
{% if not is_incremental() %}

union all
SELECT 
MD5_BINARY(GR.VALUE) AS DELIVERY_LINE_DETAIL_LHK,
MD5_BINARY(GR.VALUE) AS DELIVERY_HK,
MD5_BINARY(GR.VALUE) AS DELIVERY_LINE_HK,
MD5_BINARY(GR.VALUE) AS ITEM_HK,
MD5_BINARY(GR.VALUE) AS ORDER_HEADER_HK,
MD5_BINARY(GR.VALUE) AS ORDER_LINE_HK,
MD5_BINARY(GR.VALUE) AS PLANT_HK,
MD5_BINARY(GR.VALUE) AS GOODS_STORAGE_LOCATION_HK,
MD5_BINARY(GR.VALUE) AS DISTRIBUTION_CHANNEL_HK,
MD5_BINARY(GR.VALUE) AS DIVISION_HK,
MD5_BINARY(GR.VALUE) AS COST_CENTER_HK,
CONVERT_TIMEZONE('UTC','1900-01-01'::TIMESTAMP) AS LOAD_DTS,
'USAZET.SNOWFLAKE.FBIN.DERIVED' AS REC_SRC
FROM
TABLE(strtok_split_to_table('0|-1|-2', '|')) AS GR
{% endif %}
