---- SRC LAYER ----
WITH
SRC_a              as ( SELECT CAPACITY_HK, CONFIRMATION_UOM_HK, COST_CENTER_HK, LOAD_DTS, MATERIAL_BASE_UOM_HK, ORDER_CONFIRMATION_HK, PRODUCTION_ORDER_CONFIRMATION_LHK, PRODUCTION_ORDER_HK, PRODUCTION_ORDER_LINE_HK, REC_SRC, ROUTING_HK FROM {{ ref('v_psa_stg_order_confirmation__winn_sap') }} as SRC 
                        QUALIFY (ROW_NUMBER() OVER(PARTITION BY PRODUCTION_ORDER_CONFIRMATION_LHK ORDER BY LOAD_DTS ))=1 )

/*
SRC_a              as ( SELECT * FROM STAGING.V_PSA_STG_ORDER_CONFIRMATION__WINN_SAP )
*/
---- LOGIC LAYER ----

, LOGIC_a as (
    SELECT
        PRODUCTION_ORDER_CONFIRMATION_LHK
      , PRODUCTION_ORDER_HK
      , PRODUCTION_ORDER_LINE_HK
      , COST_CENTER_HK
      , CAPACITY_HK
      , MATERIAL_BASE_UOM_HK
      , CONFIRMATION_UOM_HK
      , ORDER_CONFIRMATION_HK
      , ROUTING_HK
      , LOAD_DTS
      , REC_SRC
    FROM SRC_a
)
---- RENAME LAYER ----

, RENAME_a as (
    SELECT
        PRODUCTION_ORDER_CONFIRMATION_LHK
      , PRODUCTION_ORDER_HK
      , PRODUCTION_ORDER_LINE_HK
      , COST_CENTER_HK
      , CAPACITY_HK
      , MATERIAL_BASE_UOM_HK
      , CONFIRMATION_UOM_HK
      , ORDER_CONFIRMATION_HK
      , ROUTING_HK
      , LOAD_DTS
      , REC_SRC
    FROM LOGIC_a
)
---- FILTER LAYER ----

, FILTER_a as (
    SELECT *
    FROM RENAME_a
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_a
)

---- FINAL LAYER ----
SELECT
          PRODUCTION_ORDER_CONFIRMATION_LHK
        , PRODUCTION_ORDER_HK
        , PRODUCTION_ORDER_LINE_HK
        , COST_CENTER_HK
        , CAPACITY_HK
        , MATERIAL_BASE_UOM_HK
        , CONFIRMATION_UOM_HK
        , ORDER_CONFIRMATION_HK
        , ROUTING_HK
        , LOAD_DTS
        , REC_SRC
FROM JOIN_RESULT
{% if is_incremental() %}
WHERE NOT EXISTS (
    SELECT 1 
    FROM {{ this }} existing
    WHERE existing.PRODUCTION_ORDER_CONFIRMATION_LHK = JOIN_RESULT.PRODUCTION_ORDER_CONFIRMATION_LHK
)
