---- SRC LAYER ----
WITH
SRC_MARA           as ( SELECT BASE_MATERIAL_HK, DIVISION_HK, ITEM_HK, LNK_ITEM_BASE_MATERIAL_DIVISION_HK, LOAD_DTS, REC_SRC FROM {{ ref('v_psa_stg_item_master__moen_sap') }} as SRC 
                        QUALIFY ROW_NUMBER() OVER(PARTITION BY LNK_ITEM_BASE_MATERIAL_DIVISION_HK ORDER BY LOAD_DTS )=1 )

/*
SRC_MARA           as ( SELECT * FROM STAGING.v_psa_stg_item_master__moen_sap )
*/
---- LOGIC LAYER ----

, LOGIC_MARA as (
    SELECT
        LNK_ITEM_BASE_MATERIAL_DIVISION_HK
      , ITEM_HK
      , BASE_MATERIAL_HK
      , DIVISION_HK
      , LOAD_DTS
      , REC_SRC
    FROM SRC_MARA
)
---- RENAME LAYER ----

, RENAME_MARA as (
    SELECT
        LNK_ITEM_BASE_MATERIAL_DIVISION_HK
      , ITEM_HK
      , BASE_MATERIAL_HK
      , DIVISION_HK
      , LOAD_DTS
      , REC_SRC
    FROM LOGIC_MARA
)
---- FILTER LAYER ----

, FILTER_MARA as (
    SELECT *
    FROM RENAME_MARA
)
---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT * FROM FILTER_MARA
)

---- FINAL LAYER ----
SELECT
          LNK_ITEM_BASE_MATERIAL_DIVISION_HK
        , ITEM_HK
        , BASE_MATERIAL_HK
        , DIVISION_HK
        , LOAD_DTS
        , REC_SRC
FROM JOIN_RESULT
{% if is_incremental() %}
WHERE NOT EXISTS (
    SELECT 1 
    FROM {{ this }} existing
    WHERE existing.LNK_ITEM_BASE_MATERIAL_DIVISION_HK = JOIN_RESULT.LNK_ITEM_BASE_MATERIAL_DIVISION_HK
)
{% endif %}
{% if not is_incremental() %}

union all
SELECT 
MD5_BINARY(GR.VALUE) AS LNK_ITEM_BASE_MATERIAL_DIVISION_HK,
MD5_BINARY(GR.VALUE) AS ITEM_HK,
MD5_BINARY(GR.VALUE) AS BASE_MATERIAL_HK,
MD5_BINARY(GR.VALUE) AS DIVISION_HK,
CONVERT_TIMEZONE('UTC','1900-01-01'::TIMESTAMP) AS LOAD_DTS,
'USAZET.SNOWFLAKE.FBIN.DERIVED' AS REC_SRC
FROM
TABLE(strtok_split_to_table('0|-1|-2', '|')) AS GR
{% endif %}
