---- SRC LAYER ----
WITH
SRC_R              as ( SELECT DISTRIBUTION_CHANNEL_HK, GOODS_STORAGE_LOCATION_HK, LNK_PLANT_GOODS_STORAGE_LOCATION_HK, LOAD_DTS, PLANT_HK, REC_SRC, SALES_ORGANIZATION_HK, SUPPLIER_HK FROM {{ ref('v_psa_stg_goods_movement_storage_location__winn_sap') }} as SRC 
                        QUALIFY (ROW_NUMBER() OVER(PARTITION BY LNK_PLANT_GOODS_STORAGE_LOCATION_HK ORDER BY LOAD_DTS ))=1 )

/*
SRC_R              as ( SELECT * FROM STAGING.V_PSA_STG_INVENTORY_STORAGE_LOCATION__WINN_SAP )
*/
---- LOGIC LAYER ----

, LOGIC_R as (
    SELECT
        LNK_PLANT_GOODS_STORAGE_LOCATION_HK
      , GOODS_STORAGE_LOCATION_HK
      , PLANT_HK
      , SALES_ORGANIZATION_HK
      , DISTRIBUTION_CHANNEL_HK
      , SUPPLIER_HK
      , LOAD_DTS
      , REC_SRC
    FROM SRC_R
)
---- RENAME LAYER ----

, RENAME_R as (
    SELECT
        LNK_PLANT_GOODS_STORAGE_LOCATION_HK
      , GOODS_STORAGE_LOCATION_HK
      , PLANT_HK
      , SALES_ORGANIZATION_HK
      , DISTRIBUTION_CHANNEL_HK
      , SUPPLIER_HK
      , LOAD_DTS
      , REC_SRC
    FROM LOGIC_R
)
---- FILTER LAYER ----

, FILTER_R as (
    SELECT *
    FROM RENAME_R
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_R
)

---- FINAL LAYER ----
SELECT
          LNK_PLANT_GOODS_STORAGE_LOCATION_HK
        , GOODS_STORAGE_LOCATION_HK
        , PLANT_HK
        , SALES_ORGANIZATION_HK
        , DISTRIBUTION_CHANNEL_HK
        , SUPPLIER_HK
        , LOAD_DTS
        , REC_SRC
FROM JOIN_RESULT
{% if is_incremental() %}
WHERE NOT EXISTS (
    SELECT 1 
    FROM {{ this }} existing
    WHERE existing.LNK_PLANT_GOODS_STORAGE_LOCATION_HK = JOIN_RESULT.LNK_PLANT_GOODS_STORAGE_LOCATION_HK )
{% endif %}
{% if not is_incremental() %}

union all
SELECT 
MD5_BINARY(GR.VALUE) AS LNK_PLANT_GOODS_STORAGE_LOCATION_HK,
MD5_BINARY(GR.VALUE) AS GOODS_STORAGE_LOCATION_HK,
MD5_BINARY(GR.VALUE) AS PLANT_HK,
MD5_BINARY(GR.VALUE) AS SALES_ORGANIZATION_HK,
MD5_BINARY(GR.VALUE) AS DISTRIBUTION_CHANNEL_HK,
MD5_BINARY(GR.VALUE) AS SUPPLIER_HK,
CONVERT_TIMEZONE('UTC','1900-01-01'::TIMESTAMP) AS LOAD_DTS,
'USAZET.SNOWFLAKE.FBIN.DERIVED' AS REC_SRC
FROM
TABLE(strtok_split_to_table('0|-1|-2', '|')) AS GR
{% endif %}