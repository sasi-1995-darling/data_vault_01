---- SRC LAYER ----
WITH
SRC_c          as ( SELECT * FROM {{ ref('v_psa_stg_controlling_ledger_entry__winn_sap') }} as SRC 
                        QUALIFY (ROW_NUMBER() OVER(PARTITION BY CONTROLLING_LEDGER_ENTRY_HK ORDER BY LOAD_DTS ))=1 )

/*
SRC_c              as ( SELECT * FROM sap_ecc_prd.V_PSA_STG_CONTROLLING_LEDGER_ENTRY__WINN_SAP )
*/
---- LOGIC LAYER ----

, LOGIC_c as (
    SELECT
        CONTROLLING_LEDGER_ENTRY_HK
      , COST_OBJECT_LINE_ITEMS_HK
      , CONTROLLING_LEDGER_HEADER_HK
      , POSTING_ROW_HK
      , COST_ELEMENT_HK
      , LEDGER_HK
      , CONTROLLING_AREA_HK
      , LOAD_DTS
      , REC_SRC
    FROM SRC_c
)
---- RENAME LAYER ----

, RENAME_c as (
    SELECT
        CONTROLLING_LEDGER_ENTRY_HK
      , COST_OBJECT_LINE_ITEMS_HK
      , CONTROLLING_LEDGER_HEADER_HK
      , POSTING_ROW_HK
      , COST_ELEMENT_HK
      , LEDGER_HK
      , CONTROLLING_AREA_HK
      , LOAD_DTS
      , REC_SRC
    FROM LOGIC_c
)
---- FILTER LAYER ----

, FILTER_c as (
    SELECT *
    FROM RENAME_c
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_c
)

---- FINAL LAYER ----
SELECT
          CONTROLLING_LEDGER_ENTRY_HK
        , COST_OBJECT_LINE_ITEMS_HK
        , CONTROLLING_LEDGER_HEADER_HK
        , POSTING_ROW_HK
        , COST_ELEMENT_HK
        , LEDGER_HK
        , CONTROLLING_AREA_HK
        , LOAD_DTS
        , REC_SRC
FROM JOIN_RESULT
{% if is_incremental() %}
WHERE NOT EXISTS (
    SELECT 1 
    FROM {{ this }} existing
    WHERE existing.COST_OBJECT_LINE_ITEMS_HK= JOIN_RESULT.COST_OBJECT_LINE_ITEMS_HK
)
{% endif %}

{% if not is_incremental() %}
union all
SELECT 

MD5_BINARY(GR.VALUE) AS CONTROLLING_LEDGER_ENTRY_HK
, MD5_BINARY(GR.VALUE) AS COST_OBJECT_LINE_ITEMS_HK
, MD5_BINARY(GR.VALUE) AS CONTROLLING_LEDGER_HEADER_HK
, MD5_BINARY(GR.VALUE) AS POSTING_ROW_HK
, MD5_BINARY(GR.VALUE) AS COST_ELEMENT_HK
, MD5_BINARY(GR.VALUE) AS LEDGER_HK
, MD5_BINARY(GR.VALUE) AS CONTROLLING_AREA_HK
, CONVERT_TIMEZONE('UTC','1900-01-01')  AS LOAD_DTS
, 'USAZET.SNOWFLAKE.FBIN.DERIVED' AS REC_SRC
FROM
TABLE(strtok_split_to_table('0|-1|-2', '|')) AS GR
{% endif %}