-- SRC LAYER --
WITH
SRC_VBAP           as ( SELECT CUSTOMER_BILLTO_HK, CUSTOMER_INSURANCEPARTNER_HK, CUSTOMER_PAYER_HK, CUSTOMER_SHIPTO_HK, CUSTOMER_SOLDTO_HK, DISTRIBUTION_CHANNEL_HK,
                        DIVISION_HK, ITEM_HK, LOAD_DTS, ORDER_HEADER_HK, ORDER_LINE_HK, PLANT_HK, REC_SRC, SALES_ORGANIZATION_HK, SO_ITEM_LHK
                        FROM {{ ref('v_psa_stg_order_item__winn_sap') }} as SRC
                        QUALIFY ROW_NUMBER() OVER(PARTITION BY SO_ITEM_LHK ORDER BY LOAD_DTS )=1 )

/*
SRC_VBAP           as ( SELECT * FROM STAGING.v_psa_stg_order_item__winn_sap )
*/
-- LOGIC LAYER --

, LOGIC_VBAP as (
    SELECT
        SO_ITEM_LHK
      , ORDER_HEADER_HK
      , ORDER_LINE_HK
      , ITEM_HK
      , CUSTOMER_SOLDTO_HK
      , CUSTOMER_BILLTO_HK
      , CUSTOMER_SHIPTO_HK
      , CUSTOMER_PAYER_HK
      , CUSTOMER_INSURANCEPARTNER_HK
      , PLANT_HK
      , DIVISION_HK
      , SALES_ORGANIZATION_HK
      , DISTRIBUTION_CHANNEL_HK
      , LOAD_DTS
      , REC_SRC
    FROM SRC_VBAP
)
-- RENAME LAYER --

, RENAME_VBAP as (
    SELECT
        SO_ITEM_LHK
      , ORDER_HEADER_HK
      , ORDER_LINE_HK
      , ITEM_HK
      , CUSTOMER_SOLDTO_HK
      , CUSTOMER_BILLTO_HK
      , CUSTOMER_SHIPTO_HK
      , CUSTOMER_PAYER_HK
      , CUSTOMER_INSURANCEPARTNER_HK
      , PLANT_HK
      , DIVISION_HK
      , SALES_ORGANIZATION_HK
      , DISTRIBUTION_CHANNEL_HK
      , LOAD_DTS
      , REC_SRC
    FROM LOGIC_VBAP
)
-- FILTER LAYER --

, FILTER_VBAP as (
    SELECT *
    FROM RENAME_VBAP
)
-- JOIN LAYER --
, JOIN_RESULT as (
    SELECT * FROM FILTER_VBAP
)

-- FINAL LAYER --
SELECT
          SO_ITEM_LHK
        , ORDER_HEADER_HK
        , ORDER_LINE_HK
        , ITEM_HK
        , CUSTOMER_SOLDTO_HK
        , CUSTOMER_BILLTO_HK
        , CUSTOMER_SHIPTO_HK
        , CUSTOMER_PAYER_HK
        , CUSTOMER_INSURANCEPARTNER_HK
        , PLANT_HK
        , DIVISION_HK
        , SALES_ORGANIZATION_HK
        , DISTRIBUTION_CHANNEL_HK
        , LOAD_DTS
        , REC_SRC
FROM JOIN_RESULT
{% if is_incremental() %}
WHERE NOT EXISTS (
    SELECT 1 
    FROM {{ this }} existing
    WHERE existing.SO_ITEM_LHK = JOIN_RESULT.SO_ITEM_LHK
)
{% endif %}
{% if not is_incremental() %}
UNION ALL
SELECT
    MD5_BINARY(GR.VALUE) AS SO_ITEM_LHK
  , MD5_BINARY(GR.VALUE) AS ORDER_HEADER_HK
  , MD5_BINARY(GR.VALUE) AS ORDER_LINE_HK
  , MD5_BINARY(GR.VALUE) AS ITEM_HK
  , MD5_BINARY(GR.VALUE) AS CUSTOMER_SOLDTO_HK
  , MD5_BINARY(GR.VALUE) AS CUSTOMER_BILLTO_HK
  , MD5_BINARY(GR.VALUE) AS CUSTOMER_SHIPTO_HK
  , MD5_BINARY(GR.VALUE) AS CUSTOMER_PAYER_HK
  , MD5_BINARY(GR.VALUE) AS CUSTOMER_INSURANCEPARTNER_HK
  , MD5_BINARY(GR.VALUE) AS PLANT_HK
  , MD5_BINARY(GR.VALUE) AS DIVISION_HK
  , MD5_BINARY(GR.VALUE) AS SALES_ORGANIZATION_HK
  , MD5_BINARY(GR.VALUE) AS DISTRIBUTION_CHANNEL_HK
  , CONVERT_TIMEZONE('UTC', '1900-01-01'::TIMESTAMP) AS LOAD_DTS
  , 'USAZET.SNOWFLAKE.FBIN.DERIVED' AS REC_SRC
FROM TABLE(strtok_split_to_table('0|-1|-2', '|')) AS GR
{% endif %}