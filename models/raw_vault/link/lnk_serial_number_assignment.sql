---- SRC LAYER ----
WITH
SRC_LSA            as ( SELECT HANDLING_UNIT_HK, LOAD_DTS, OBJECT_LIST_HK, REC_SRC, LNK_SERIAL_NUMBER_HU_ASSIGNMENT_HK FROM {{ ref('v_psa_stg_serial_number_assignment__winn_sap') }} as SRC 
                        QUALIFY (ROW_NUMBER() OVER(PARTITION BY LNK_SERIAL_NUMBER_HU_ASSIGNMENT_HK ORDER BY LOAD_DTS DESC))=1 )

/*
SRC_LSA            as ( SELECT * FROM STAGING.v_psa_stg_serial_number_assignment__winn_sap )
*/
---- LOGIC LAYER ----

, LOGIC_LSA as (
    SELECT
        LNK_SERIAL_NUMBER_HU_ASSIGNMENT_HK
      , OBJECT_LIST_HK
      , HANDLING_UNIT_HK
      , LOAD_DTS
      , REC_SRC
    FROM SRC_LSA
)
---- RENAME LAYER ----

, RENAME_LSA as (
    SELECT
        LNK_SERIAL_NUMBER_HU_ASSIGNMENT_HK
      , OBJECT_LIST_HK
      , HANDLING_UNIT_HK
      , LOAD_DTS
      , REC_SRC
    FROM LOGIC_LSA
)
---- FILTER LAYER ----

, FILTER_LSA as (
    SELECT *
    FROM RENAME_LSA
)
---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT * FROM FILTER_LSA
)

---- FINAL LAYER ----
SELECT
          LNK_SERIAL_NUMBER_HU_ASSIGNMENT_HK
        , OBJECT_LIST_HK
        , HANDLING_UNIT_HK
        , LOAD_DTS
        , REC_SRC
FROM JOIN_RESULT
{% if is_incremental() %}
WHERE NOT EXISTS (
    SELECT 1 
    FROM {{ this }} existing
    WHERE existing.LNK_SERIAL_NUMBER_HU_ASSIGNMENT_HK = JOIN_RESULT.LNK_SERIAL_NUMBER_HU_ASSIGNMENT_HK
)
{% endif %}
--this is to consolidate records coming from 2 diff tables with the same bkcc
QUALIFY (ROW_NUMBER() OVER(PARTITION BY LNK_SERIAL_NUMBER_HU_ASSIGNMENT_HK ORDER BY LOAD_DTS DESC))=1
{% if not is_incremental() %}

union all
SELECT 
 MD5_BINARY(GR.VALUE) AS LNK_SERIAL_NUMBER_HU_ASSIGNMENT_HK
, MD5_BINARY(GR.VALUE) AS OBJECT_LIST_HK
, MD5_BINARY(GR.VALUE) AS HANDLING_UNIT_HK
, CONVERT_TIMEZONE('UTC','1900-01-01'::TIMESTAMP)  AS LOAD_DTS
, 'USAZET.SNOWFLAKE.FBIN.DERIVED' AS REC_SRC
FROM
TABLE(strtok_split_to_table('0|-1|-2', '|')) AS GR
{% endif %}