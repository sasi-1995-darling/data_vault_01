      , EXCHANGE_RATE
      , REFERENCE_TRANSACTION_TYPE
      , REFERENCE_KEY
      , EXCHANGE_RATE_2ND_CURRENCY
      , EXCHANGE_RATE_TYPE
      , CURRENCY_TYPE_2
      , EXCHANGE_RATE_TYPE_2
      , DOCUMENT_HEADER_TEXT
      , DOCUMENT_STATUS
      , REVERSAL_DOCUMENT_NUMBER
      , FISCAL_YEAR_REVERSAL_DOCUMENT__YYYY
      , REVERSAL_REASON
      , BKCC
      , REC_SRC
      , IS_DELETED
    FROM LOGIC_P
)
---- FILTER LAYER ----

, FILTER_P as (
    SELECT *
    FROM RENAME_P
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_P
)

---- FINAL LAYER ----
