, LOGIC_P as (
    SELECT
        GENERAL_LEDGER_HK
      , COMPANY_CODE_BK
      , ACCOUNTING_DOC_NUM_BK
      , FISCAL_YEAR_BK
      , ACCOUNTING_YEAR
      , DOCUMENT_TYPE
      , DOCUMENT_DATE__YYYYMMDD
      , POSTING_DATE__YYYYMMDD
      , FISCAL_PERIOD
      , DAY_OF_ENTRY__YYYYMMDD
      , TIME_OF_ENTRY
      , REFERENCE_DOCUMENT_NUMBER
