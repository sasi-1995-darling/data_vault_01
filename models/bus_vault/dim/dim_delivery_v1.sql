---- SRC LAYER ----
WITH
SRC_D              as ( SELECT ACTUAL_GOODS_ISSUE_DATE__YYYYMMDD, BKCC, DELIVERY_BK, DELIVERY_HK, DELIVERY_ID, PLANNED_DELIVERY_DATE__YYYYMMDD, REC_SRC, SHIPPING_POINT_ID, SHIP_TO_CUSTOMER_ID FROM {{ ref('pit_delivery') }} as SRC  )

/*
SRC_D              as ( SELECT * FROM BUS_VAULT.pit_delivery )
*/
---- LOGIC LAYER ----

, LOGIC_D as (
    SELECT
        REC_SRC
      , DELIVERY_BK
      , DELIVERY_HK
      , DELIVERY_ID
      , SHIP_TO_CUSTOMER_ID
      , SHIPPING_POINT_ID
      , ACTUAL_GOODS_ISSUE_DATE__YYYYMMDD
      , PLANNED_DELIVERY_DATE__YYYYMMDD
      , BKCC
    FROM SRC_D
)
---- RENAME LAYER ----

, RENAME_D as (
    SELECT
        REC_SRC
      , DELIVERY_BK
      , DELIVERY_HK
      , DELIVERY_ID
      , SHIP_TO_CUSTOMER_ID
      , SHIPPING_POINT_ID
      , ACTUAL_GOODS_ISSUE_DATE__YYYYMMDD
      , PLANNED_DELIVERY_DATE__YYYYMMDD
      , BKCC
    FROM LOGIC_D
)
---- FILTER LAYER ----

, FILTER_D as (
    SELECT *
    FROM RENAME_D
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_D
)

---- FINAL LAYER ----
SELECT
          REC_SRC
        , DELIVERY_BK
        , DELIVERY_HK
        , DELIVERY_ID
        , SHIP_TO_CUSTOMER_ID
        , SHIPPING_POINT_ID
        , ACTUAL_GOODS_ISSUE_DATE__YYYYMMDD
        , PLANNED_DELIVERY_DATE__YYYYMMDD
        , BKCC
FROM JOIN_RESULT
