---- SRC LAYER ----
WITH
SRC_P_PR           as ( SELECT * FROM {{ ref('pit_purchasing_record_current') }} as SRC  )

/*
SRC_P_PR           as ( SELECT * FROM BUS_VAULT.PIT_PURCHASE_RECORD_CURRENT )
*/
---- LOGIC LAYER ----

, LOGIC_P_PR as (
    SELECT
        PURCHASING_RECORD_HK
      , PURCHASING_RECORD_BK
      , COUNTRY_OF_ISSUE
      , PO_UNIT_OF_MEASURE
      , NUMERATOR_UOM_CONVERSION
      , DENOMINATOR_UOM_CONVERSION
      , BASE_UNIT_OF_MEASURE
      , PURCHASING_RECORD_DEL_IND
      , PURCHASING_RECORD_CREATION_DATE
      , REC_SRC
    FROM SRC_P_PR
)
---- RENAME LAYER ----

, RENAME_P_PR as (
    SELECT
        PURCHASING_RECORD_HK
      , PURCHASING_RECORD_BK
      , COUNTRY_OF_ISSUE
      , PO_UNIT_OF_MEASURE
      , NUMERATOR_UOM_CONVERSION
      , DENOMINATOR_UOM_CONVERSION
      , BASE_UNIT_OF_MEASURE
      , PURCHASING_RECORD_DEL_IND
      , PURCHASING_RECORD_CREATION_DATE
      , REC_SRC
    FROM LOGIC_P_PR
)
---- FILTER LAYER ----

, FILTER_P_PR as (
    SELECT *
    FROM RENAME_P_PR
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_P_PR
)

---- FINAL LAYER ----
SELECT
          PURCHASING_RECORD_HK
        , PURCHASING_RECORD_BK
        , COUNTRY_OF_ISSUE
        , PO_UNIT_OF_MEASURE
        , NUMERATOR_UOM_CONVERSION
        , DENOMINATOR_UOM_CONVERSION
        , BASE_UNIT_OF_MEASURE
        , PURCHASING_RECORD_DEL_IND
        , PURCHASING_RECORD_CREATION_DATE
        , REC_SRC
FROM JOIN_RESULT