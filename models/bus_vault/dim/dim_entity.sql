---- SRC LAYER ----
WITH
SRC_PIT            as ( SELECT ENTITY_HK, CLIENT, COMPANY, COMPANY_NAME, COUNTRY_OF_COMPANY, COMPANY_NAME_2, LANGUAGE_KEY, COMPANY_STREET_ADDRESS, COMPANY_POST_OFFICE_BOX, GLOBAL_COMPANY_ZIP_CODE, COMPANY_CITY, LOCAL_CURRENCY, MASTER_DATA_COMPANY_CODE, MASTER_DATA_CLIENT, REC_SRC, BKCC, IS_DELETED 
                        FROM {{ ref('pit_entity') }} as SRC  )

/*
SRC_PIT            as ( SELECT * FROM BUS_VAULT.PIT_ENTITY )
*/
---- LOGIC LAYER ----

, LOGIC_PIT as (
    SELECT
        ENTITY_HK
      , CLIENT
      , COMPANY
      , COMPANY_NAME
      , COUNTRY_OF_COMPANY
      , COMPANY_NAME_2
      , LANGUAGE_KEY
      , COMPANY_STREET_ADDRESS
      , COMPANY_POST_OFFICE_BOX
      , GLOBAL_COMPANY_ZIP_CODE
      , COMPANY_CITY
      , LOCAL_CURRENCY
      , MASTER_DATA_COMPANY_CODE
      , MASTER_DATA_CLIENT
      , REC_SRC
      , BKCC
      , IS_DELETED
    FROM SRC_PIT
)
---- RENAME LAYER ----

, RENAME_PIT as (
    SELECT
        ENTITY_HK
      , CLIENT
      , COMPANY
      , COMPANY_NAME
      , COUNTRY_OF_COMPANY
      , COMPANY_NAME_2
      , LANGUAGE_KEY
      , COMPANY_STREET_ADDRESS
      , COMPANY_POST_OFFICE_BOX
      , GLOBAL_COMPANY_ZIP_CODE
      , COMPANY_CITY
      , LOCAL_CURRENCY
      , MASTER_DATA_COMPANY_CODE
      , MASTER_DATA_CLIENT
      , REC_SRC
      , BKCC
      , IS_DELETED
    FROM LOGIC_PIT
)
---- FILTER LAYER ----

, FILTER_PIT as (
    SELECT *
    FROM RENAME_PIT
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_PIT
)

---- FINAL LAYER ----
SELECT
          ENTITY_HK
        , CLIENT
        , COMPANY
        , COMPANY_NAME
        , COUNTRY_OF_COMPANY
        , COMPANY_NAME_2
        , LANGUAGE_KEY
        , COMPANY_STREET_ADDRESS
        , COMPANY_POST_OFFICE_BOX
        , GLOBAL_COMPANY_ZIP_CODE
        , COMPANY_CITY
        , LOCAL_CURRENCY
        , MASTER_DATA_COMPANY_CODE
        , MASTER_DATA_CLIENT
        , REC_SRC
        , BKCC
        , IS_DELETED
FROM JOIN_RESULT
