---- SRC LAYER ----
WITH
SRC_GL_ACTIVITY         as ( SELECT * FROM {{ ref('pit_gl_activity_type') }} as SRC  )

/*
SRC_GL_ACTIVITY            as ( SELECT * FROM BUS_VAULT.pit_gl_activity_type )
*/
---- LOGIC LAYER ----

, LOGIC_GL_ACTIVITY as (
    SELECT
      GL_ACTIVITY_TYPE_HK
    , CONTROLLING_AREA_BK
    , ACTIVITY_TYPE_BK
    , VALID_DATE__YYYYMMDD
    , VALID_TO_DATE__YYYYMMDD
    , VALID_FROM_DATE__YYYYMMDD
    , ACTIVITY_UNIT
    , ACTIVITY_CATEGORY
    , CREATE_DATE__YYYYMMDD
    , ENTERED_BY
    , OUTPUT_UNIT
    , OUTPUT_FACTOR
    , ALLOCATION_ELEMENT
    , LOCK_FLAG
    , ORIGIN_GROUP
    , ALLOCATION_PRICE_IND
    , PRICE_CALCULATION_IND
    , ACTUAL_PRICE_ALLOCATION
    , PSA_DELETE_IND
    , SAT_REC_SRC
    , BKCC
    , REC_SRC
    , IS_DELETED
    FROM SRC_GL_ACTIVITY
)
---- RENAME LAYER ----

, RENAME_GL_ACTIVITY as (
    SELECT
      GL_ACTIVITY_TYPE_HK
    , CONTROLLING_AREA_BK
    , ACTIVITY_TYPE_BK
    , VALID_DATE__YYYYMMDD
    , VALID_TO_DATE__YYYYMMDD
    , VALID_FROM_DATE__YYYYMMDD
    , ACTIVITY_UNIT
    , ACTIVITY_CATEGORY
    , CREATE_DATE__YYYYMMDD
    , ENTERED_BY
    , OUTPUT_UNIT
    , OUTPUT_FACTOR
    , ALLOCATION_ELEMENT
    , LOCK_FLAG
    , ORIGIN_GROUP
    , ALLOCATION_PRICE_IND
    , PRICE_CALCULATION_IND
    , ACTUAL_PRICE_ALLOCATION
    , PSA_DELETE_IND
    , SAT_REC_SRC
    , BKCC
    , REC_SRC
    , IS_DELETED
    FROM LOGIC_GL_ACTIVITY
)
---- FILTER LAYER ----

, FILTER_GL_ACTIVITY as (
    SELECT *
    FROM RENAME_GL_ACTIVITY
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_GL_ACTIVITY
)

---- FINAL LAYER ----
SELECT
      GL_ACTIVITY_TYPE_HK
    , CONTROLLING_AREA_BK
    , ACTIVITY_TYPE_BK
    , VALID_DATE__YYYYMMDD
    , VALID_TO_DATE__YYYYMMDD
    , VALID_FROM_DATE__YYYYMMDD
    , ACTIVITY_UNIT
    , ACTIVITY_CATEGORY
    , CREATE_DATE__YYYYMMDD
    , ENTERED_BY
    , OUTPUT_UNIT
    , OUTPUT_FACTOR
    , ALLOCATION_ELEMENT
    , LOCK_FLAG
    , ORIGIN_GROUP
    , ALLOCATION_PRICE_IND
    , PRICE_CALCULATION_IND
    , ACTUAL_PRICE_ALLOCATION
    , PSA_DELETE_IND
    , SAT_REC_SRC
    , BKCC
    , REC_SRC
    , IS_DELETED
FROM JOIN_RESULT
