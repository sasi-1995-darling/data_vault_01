WITH
SRC_P              as ( SELECT ACTIVITY_GROUP, BKCC, CLASSIFICATION, CO_ACTION_SUBGROUP, FLAG_PROCEDURE_ASSIGN_CO_DOC_NUMBER, FLAG_PROCEDURE_CHANGE_USER_STATUS, INDICATOR_STATUS_ADMIN_TRANSACTION, IND_ACTIVITY_FUNDS_MANAGEMENT, IND_TRANSACTION_COEJ, IND_TRANSACTION_COEJL, IND_TRANSACTION_COEJR, IND_TRANSACTION_COEJT, IND_TRANSACTION_COEP, IND_TRANSACTION_COEPB, IND_TRANSACTION_COEPL, IND_TRANSACTION_COEPR, IND_TRANSACTION_COEPT, IND_TRANSACTION_COFP, IND_TRANSACTION_COOI, IND_TRANSACTION_COSP, IND_TRANSACTION_COSS, IND_TRANSACTION_CO_PERIOD_LOCK, IS_DELETED, PROCEDURE_JOINT_VENTURES, REC_SRC, STATUS_CHECK_TRANSACTION, TRANSACTION_FOR_CO_DOC_NUMBER_ASSIGNMENT, COST_TRANSACTION_TYPE, COST_TRANSACTION_TYPE_BK, COST_TRANSACTION_TYPE_HK, VALUE_CATEGORY FROM {{ ref('pit_transaction_type_current') }} as SRC  )

/*
SRC_P              as ( SELECT * FROM RAW_VAULT.PIT_TRANSACTION_TYPE_CURRENT )
*/ 
---- LOGIC LAYER ----

, LOGIC_P as (
    SELECT
        COST_TRANSACTION_TYPE_HK
      , COST_TRANSACTION_TYPE_BK
      , COST_TRANSACTION_TYPE
      , INDICATOR_STATUS_ADMIN_TRANSACTION
      , IND_TRANSACTION_CO_PERIOD_LOCK
      , IND_TRANSACTION_COEP
      , IND_TRANSACTION_COEJ
      , IND_TRANSACTION_COOI
      , IND_TRANSACTION_COSP
      , IND_TRANSACTION_COSS
      , IND_TRANSACTION_COEPL
      , IND_TRANSACTION_COEJL
      , IND_TRANSACTION_COEPR
      , IND_TRANSACTION_COEJR
      , IND_TRANSACTION_COEPT
      , IND_TRANSACTION_COEJT
      , IND_TRANSACTION_COEPB
      , IND_TRANSACTION_COFP
      , IND_ACTIVITY_FUNDS_MANAGEMENT
      , BKCC
      , REC_SRC
      , IS_DELETED
    FROM SRC_P
)
---- RENAME LAYER ----

, RENAME_P as (
    SELECT
        COST_TRANSACTION_TYPE_HK
      , COST_TRANSACTION_TYPE_BK
      , COST_TRANSACTION_TYPE
      , INDICATOR_STATUS_ADMIN_TRANSACTION
      , IND_TRANSACTION_CO_PERIOD_LOCK
      , IND_TRANSACTION_COEP
      , IND_TRANSACTION_COEJ
      , IND_TRANSACTION_COOI
      , IND_TRANSACTION_COSP
      , IND_TRANSACTION_COSS
      , IND_TRANSACTION_COEPL
      , IND_TRANSACTION_COEJL
      , IND_TRANSACTION_COEPR
      , IND_TRANSACTION_COEJR
      , IND_TRANSACTION_COEPT
      , IND_TRANSACTION_COEJT
      , IND_TRANSACTION_COEPB
      , IND_TRANSACTION_COFP
      , IND_ACTIVITY_FUNDS_MANAGEMENT
      , BKCC
      , REC_SRC
      , IS_DELETED
    FROM LOGIC_P
)
---- FILTER LAYER ----

, FILTER_P as (
    SELECT *
    FROM RENAME_P
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_P
)

---- FINAL LAYER ----
SELECT
          COST_TRANSACTION_TYPE_HK
        , COST_TRANSACTION_TYPE_BK
        , COST_TRANSACTION_TYPE
        , INDICATOR_STATUS_ADMIN_TRANSACTION
        , CASE
        WHEN IND_TRANSACTION_COEP = 'X' THEN 'COEP'
        WHEN IND_TRANSACTION_COEJ = 'X' THEN 'COEJ'
        WHEN IND_TRANSACTION_COOI = 'X' THEN 'COOI'
        WHEN IND_TRANSACTION_COSP = 'X' THEN 'COSP'
        WHEN IND_TRANSACTION_COSS = 'X' THEN 'COSS'
        WHEN IND_TRANSACTION_COEPL = 'X' THEN 'COEPL'
        WHEN IND_TRANSACTION_COEJL = 'X' THEN 'COEJL'
        WHEN IND_TRANSACTION_COEPR = 'X' THEN 'COEPR'
        WHEN IND_TRANSACTION_COEJR = 'X' THEN 'COEJR'
        WHEN IND_TRANSACTION_COEPT = 'X' THEN 'COEPT'
        WHEN IND_TRANSACTION_COEJT = 'X' THEN 'COEJT'
        WHEN IND_TRANSACTION_COEPB = 'X' THEN 'COEPB'
        WHEN IND_TRANSACTION_COFP = 'X' THEN 'COFP'
        WHEN IND_TRANSACTION_CO_PERIOD_LOCK = 'X' THEN 'PERIOD_LOCK'
        WHEN IND_ACTIVITY_FUNDS_MANAGEMENT = 'X' THEN 'FUNDS'
        ELSE 'ADMIN'
        END AS TRANSACTION_SOURCE
        , BKCC
        , REC_SRC
        , IS_DELETED
FROM JOIN_RESULT