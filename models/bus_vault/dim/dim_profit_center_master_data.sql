/*
SRC_PPC        as ( SELECT * FROM BUS_VAULT.PIT_PROFIT_CENTER_MASTER_DATA )
*/
---- LOGIC LAYER ----

, LOGIC_PPC as (
    SELECT
        OBJECT_NUMBER_HK
      , CLIENT
      , PROFIT_CENTER
      , VALID_TO_DATE__YYYYMMDD
      , CONTROLLING_AREA
      , VALID_FROM_DATE__YYYYMMDD
      , CREATED_ON_DATE__YYYYMMDD
      , ENTERED_BY
      , DEPARTMENT
      , PROFIT_CENTER_RESPONSIBLE_PERSON
      , COUNTRY_KEY
      , HOUSE_NUMBER_AND_STREET
      , POSTAL_CODE
      , LANGUAGE_KEY
      , PROFIT_CENTER_AREA
      , TAX_JURISDICTION
      , REGION
      , LOCK_IND
      , GENERAL_NAME
      , LONG_TEXT
      , SEARCH_TERM_FOR_MATCHCODE_SEARCH
      , REC_SRC
      , BKCC
      , IS_DELETED
    FROM SRC_PPC
)
---- RENAME LAYER ----

, RENAME_PPC as (
    SELECT
        OBJECT_NUMBER_HK
      , CLIENT
      , PROFIT_CENTER
      , VALID_TO_DATE__YYYYMMDD
      , CONTROLLING_AREA
      , VALID_FROM_DATE__YYYYMMDD
      , CREATED_ON_DATE__YYYYMMDD
      , ENTERED_BY
      , DEPARTMENT
      , PROFIT_CENTER_RESPONSIBLE_PERSON
      , COUNTRY_KEY
      , HOUSE_NUMBER_AND_STREET
      , POSTAL_CODE
      , LANGUAGE_KEY
      , PROFIT_CENTER_AREA
      , TAX_JURISDICTION
      , REGION
      , LOCK_IND
      , GENERAL_NAME
      , LONG_TEXT
      , SEARCH_TERM_FOR_MATCHCODE_SEARCH
      , REC_SRC
      , BKCC
      , IS_DELETED
    FROM LOGIC_PPC
)
---- FILTER LAYER ----

, FILTER_PPC as (
    SELECT *
    FROM RENAME_PPC
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_PPC
)

---- FINAL LAYER ----
SELECT
          OBJECT_NUMBER_HK
        , CLIENT
        , PROFIT_CENTER
        , VALID_TO_DATE__YYYYMMDD
        , CONTROLLING_AREA
        , VALID_FROM_DATE__YYYYMMDD
        , CREATED_ON_DATE__YYYYMMDD
        , ENTERED_BY
        , DEPARTMENT
        , PROFIT_CENTER_RESPONSIBLE_PERSON
        , COUNTRY_KEY
        , HOUSE_NUMBER_AND_STREET
        , POSTAL_CODE
        , LANGUAGE_KEY
        , PROFIT_CENTER_AREA
        , TAX_JURISDICTION
        , REGION
        , LOCK_IND
        , GENERAL_NAME
        , LONG_TEXT
        , SEARCH_TERM_FOR_MATCHCODE_SEARCH
        , REC_SRC
        , BKCC
        , IS_DELETED
FROM JOIN_RESULT
