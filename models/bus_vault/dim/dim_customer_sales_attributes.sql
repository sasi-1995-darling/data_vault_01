*/
---- LOGIC LAYER ----

, LOGIC_PBCSA as (
    SELECT
        CUSTOMER_SALES_ATTRIBUTES_KEY
      , CUSTOMER_HK
      , CUSTOMER_BK
      , CUSTOMER
      , SALES_ORGANIZATION_HK
      , SALES_ORGANIZATION_BK
      , SALES_ORGANIZATION
      , DISTRIBUTION_CHANNEL_HK
      , DISTRIBUTION_CHANNEL_BK
      , DISTRIBUTION_CHANNEL
      , DIVISION_HK
      , DIVISION_BK
      , DIVISION
      , ACCOUNT_NUMBER
      , ACCOUNT_NAME
      , REPORTING_DISTRICT
      , SALES_GROUP
      , SALES_OFFICE
      , CUSTOMER_PRICE_ACCOUNT
      , KEY_ACCOUNT
      , GROUP_KEY_ACCOUNT
      , BUYING_GROUP_ID
      , APO_GROUP
      , APO_FORECAST_ACCOUNT
      , CUSTOMER_LEAD_DAYS
      , CUSTOMER_EARLY_SHIP_FLAG
      , TEAM_CODE
      , REC_SRC
      , BKCC
    FROM SRC_PBCSA
)
---- RENAME LAYER ----

, RENAME_PBCSA as (
    SELECT
        CUSTOMER_SALES_ATTRIBUTES_KEY
      , CUSTOMER_HK
      , CUSTOMER_BK
      , CUSTOMER
      , SALES_ORGANIZATION_HK
      , SALES_ORGANIZATION_BK
