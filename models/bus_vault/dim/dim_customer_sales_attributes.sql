      , SALES_OFFICE
      , CUSTOMER_PRICE_ACCOUNT
      , KEY_ACCOUNT
      , GROUP_KEY_ACCOUNT
      , BUYING_GROUP_ID
      , APO_GROUP
      , APO_FORECAST_ACCOUNT
      , CUSTOMER_LEAD_DAYS
      , CUSTOMER_EARLY_SHIP_FLAG
      , TEAM_CODE
      , REC_SRC
      , BKCC
    FROM LOGIC_PBCSA
)
---- FILTER LAYER ----

, FILTER_PBCSA as (
    SELECT *
    FROM RENAME_PBCSA
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_PBCSA
)

---- FINAL LAYER ----
