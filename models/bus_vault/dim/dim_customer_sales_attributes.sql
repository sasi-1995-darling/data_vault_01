SRC_PBCSA          as ( SELECT ACCOUNT_NAME, ACCOUNT_NUMBER, APO_FORECAST_ACCOUNT, APO_GROUP, BKCC, BUYING_GROUP_ID, CUSTOMER, CUSTOMER_BK, CUSTOMER_EARLY_SHIP_FLAG, CUSTOMER_HK, CUSTOMER_LEAD_DAYS, CUSTOMER_PRICE_ACCOUNT, CUSTOMER_SALES_ATTRIBUTES_KEY, DISTRIBUTION_CHANNEL, DISTRIBUTION_CHANNEL_BK, DISTRIBUTION_CHANNEL_HK, DIVISION, DIVISION_BK, DIVISION_HK, GROUP_KEY_ACCOUNT, KEY_ACCOUNT, REC_SRC, REPORTING_DISTRICT, SALES_GROUP, SALES_OFFICE, SALES_ORGANIZATION, SALES_ORGANIZATION_BK, SALES_ORGANIZATION_HK, TEAM_CODE FROM {{ ref('pb_customer_sales_attributes') }} as SRC  )

