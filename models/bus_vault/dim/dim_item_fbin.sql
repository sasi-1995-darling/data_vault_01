SRC_pbi            as ( SELECT BASE_MATERIAL, BKCC, BRAND, D_CHAIN_CODE, FORECAST_BASE_MATERIAL, ITEM_ARCHITECTURE, ITEM_ARCHITECTURE_DETAIL,
                        ITEM_BASE_UOM, ITEM_CATEGORY, ITEM_CLASS, ITEM_FINISH, ITEM_ID, ITEM_NUMBER, ITEM_PRICE_BAND, ITEM_PRODUCT_LINE,
