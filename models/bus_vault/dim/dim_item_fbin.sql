                        ITEM_SUB_CATEGORY, ITEM_SUB_CLASS, ITEM_TITLE, ITEM_TYPE_CODE, ITEM_TYPE_DESCRIPTION, LAUNCH_DATE__YYYYMMDD,
                        LAUNCH_DATE_SOURCE, PNS_PRICE_BAND, REC_SRC, ULTIMATE_ITEM_SUPPLY_SOURCE FROM {{ ref('pb_item') }} as SRC
                        where 1=1 )
