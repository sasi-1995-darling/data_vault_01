      , PRODUCTION_SUPERVISOR
      , SCHEDULING_MARGIN_KEY_FOR_FLOAT
      , SCHEDULING_TYPE
      , REC_SRC
      , BKCC
    FROM LOGIC_D
)
---- FILTER LAYER ----

, FILTER_D as (
    SELECT *
    FROM RENAME_D
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_D
)

