---- RENAME LAYER ----

, RENAME_SUP as (
    SELECT
        SUPPLIER_SITE_KEY
      , SUPPLIER_BK
      , MDM_SUPPLIER_BK
      , MDM_SUPPLIER_SITE_BK
      , MDM_GOLDEN_RECORD
