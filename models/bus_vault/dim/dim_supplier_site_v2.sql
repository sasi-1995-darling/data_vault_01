SRC_SUP            as ( SELECT * FROM BUS_VAULT.pb_supplier_site )
*/
---- LOGIC LAYER ----

, LOGIC_SUP as (
    SELECT
        SUPPLIER_SITE_KEY
      , SUPPLIER_BK
      , MDM_SUPPLIER_BK
      , MDM_SUPPLIER_SITE_BK
      , MDM_GOLDEN_RECORD
