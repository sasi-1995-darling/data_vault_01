      , MDM_CITY
      , MDM_STATE
      , MDM_POSTAL_CODE
      , MDM_COUNTRY
      , MDM_TAX_NUMBER
      , MDM_SUPPLIER_TYPE
      , MDM_SOURCE_LAST_RUN_DATE__YYYYMMDD
      , MDM_INACTIVE_DATE__YYYYMMDD
      , MDM_SITE_STATUS
      , MDM_PHONE_NUMBER
      , MDM_FAX_NUMBER
      , MDM_PRIMARY_EMAIL_ADDRESS
      , REC_SRC
      , BKCC
