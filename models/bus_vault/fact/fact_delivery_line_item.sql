---- SRC LAYER ----
WITH
SRC_D              as ( SELECT ACTUAL_GOODS_ISSUE_DATE__YYYYMMDD, BKCC, DELIVERED_QUANTITY, DELIVERY_BK, DELIVERY_HK, DELIVERY_ID, DELIVERY_ITEM_ID, DELIVERY_LINE_DETAIL_LHK, ITEM_BK, ITEM_GROSS_WEIGHT, ITEM_HK, ITEM_NET_WEIGHT, ITEM_VOLUME, ITEM_VOLUME_UNIT, ITEM_WEIGHT_UNIT, MASTER_DATA_GROSS_WEIGHT, MASTER_DATA_WEIGHT_UNIT, MATERIAL_GROUP_ID, MATERIAL_ID, PIT_LOAD_DTS, PLANNED_DELIVERY_DATE__YYYYMMDD, PLANT_ID, REC_SRC, SALES_UNIT, SHIPPING_POINT_ID, SHIP_TO_CUSTOMER_ID, STORAGE_LOCATION_ID, SAT_WINN_PSA_DELETE_IND FROM {{ ref('pb_delivery_line_item') }} as SRC  )

/*
SRC_D              as ( SELECT * FROM BUS_VAULT.pb_delivery_line_item )
*/
---- LOGIC LAYER ----

, LOGIC_D as (
    SELECT
        REC_SRC
      , DELIVERY_HK
      , ITEM_HK
      , DELIVERY_LINE_DETAIL_LHK
      , DELIVERY_BK
      , ITEM_BK
      , DELIVERY_ID
      , DELIVERY_ITEM_ID
      , SHIP_TO_CUSTOMER_ID
      , SHIPPING_POINT_ID
      , MATERIAL_ID
      , PLANT_ID
      , STORAGE_LOCATION_ID
      , MATERIAL_GROUP_ID
      , PLANNED_DELIVERY_DATE__YYYYMMDD::INTEGER as PLANNED_DELIVERY_DATE__YYYYMMDD
      , ACTUAL_GOODS_ISSUE_DATE__YYYYMMDD::INTEGER as ACTUAL_GOODS_ISSUE_DATE__YYYYMMDD
      , DELIVERED_QUANTITY
      , SALES_UNIT
      , ITEM_GROSS_WEIGHT
      , ITEM_NET_WEIGHT
      , ITEM_WEIGHT_UNIT
      , ITEM_VOLUME
      , ITEM_VOLUME_UNIT
      , MASTER_DATA_GROSS_WEIGHT
      , MASTER_DATA_WEIGHT_UNIT
      , BKCC
      , PIT_LOAD_DTS
      , SAT_WINN_PSA_DELETE_IND
    FROM SRC_D
)
---- RENAME LAYER ----

, RENAME_D as (
    SELECT
        REC_SRC
      , DELIVERY_HK
      , ITEM_HK
      , DELIVERY_LINE_DETAIL_LHK
      , DELIVERY_BK
      , ITEM_BK
      , DELIVERY_ID
      , DELIVERY_ITEM_ID
      , SHIP_TO_CUSTOMER_ID
      , SHIPPING_POINT_ID
      , MATERIAL_ID
      , PLANT_ID
      , STORAGE_LOCATION_ID
      , MATERIAL_GROUP_ID
      , PLANNED_DELIVERY_DATE__YYYYMMDD
      , ACTUAL_GOODS_ISSUE_DATE__YYYYMMDD
      , DELIVERED_QUANTITY
      , SALES_UNIT
      , ITEM_GROSS_WEIGHT
      , ITEM_NET_WEIGHT
      , ITEM_WEIGHT_UNIT
      , ITEM_VOLUME
      , ITEM_VOLUME_UNIT
      , MASTER_DATA_GROSS_WEIGHT
      , MASTER_DATA_WEIGHT_UNIT
      , BKCC
      , PIT_LOAD_DTS AS LOAD_DTS
      , SAT_WINN_PSA_DELETE_IND AS IS_DELETED 
    FROM LOGIC_D
)
---- FILTER LAYER ----

, FILTER_D as (
    SELECT *
    FROM RENAME_D
    WHERE IS_DELETED = 'N' OR IS_DELETED IS NULL
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_D
)

---- FINAL LAYER ----
SELECT
          REC_SRC
        , DELIVERY_HK
        , ITEM_HK
        , DELIVERY_LINE_DETAIL_LHK
        , DELIVERY_BK
        , ITEM_BK
        , DELIVERY_ID
        , DELIVERY_ITEM_ID
        , SHIP_TO_CUSTOMER_ID
        , SHIPPING_POINT_ID
        , MATERIAL_ID
        , PLANT_ID
        , STORAGE_LOCATION_ID
        , MATERIAL_GROUP_ID
        , PLANNED_DELIVERY_DATE__YYYYMMDD
        , ACTUAL_GOODS_ISSUE_DATE__YYYYMMDD
        , DELIVERED_QUANTITY
        , SALES_UNIT
        , ITEM_GROSS_WEIGHT
        , ITEM_NET_WEIGHT
        , ITEM_WEIGHT_UNIT
        , ITEM_VOLUME
        , ITEM_VOLUME_UNIT
        , MASTER_DATA_GROSS_WEIGHT
        , MASTER_DATA_WEIGHT_UNIT
        , BKCC
        , LOAD_DTS
        , IS_DELETED
FROM JOIN_RESULT
