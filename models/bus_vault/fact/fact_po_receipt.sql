---- SRC LAYER ----
WITH
SRC_PIT            as ( SELECT BKCC, ITEM_BK, ITEM_HK, LEGAL_ENTITY_BK, LEGAL_ENTITY_HK, MATERIAL_DOCUMENT_ITEM, MATERIAL_DOCUMENT_NUMBER, NEED_BY_DATE_EARLIEST__YYYYMMDD, NEED_BY_DATE_LATEST__YYYYMMDD, ORIGINAL_PROMISED_DATE__YYYYMMDD, PLANT_BK, PLANT_HK, PO_HEADER_BK, PO_HEADER_HK, PO_LINE_NUMBER, PO_LINE_RECEIPT_IND_HK, PO_NUMBER, PO_RECEIPT_DATE, PO_RECEIPT_PRICE, PO_RECEIPT_QUANTITY, PO_RECEIPT_VALUE, PO_RECEIPT_VALUE_LOCAL, PROMISED_DATE_EARLIEST__YYYYMMDD, PROMISED_DATE_LATEST__YYYYMMDD, REC_SRC, RELEASE_NUMBER, SUPPLIER_BK, SUPPLIER_HK, TRANSACTION_ID FROM {{ ref('pit_po_receipt_current') }} as SRC  )

/*
SRC_PIT            as ( SELECT * FROM BUS_VAULT.PIT_PO_RECEIPT_CURRENT )
*/
---- LOGIC LAYER ----

, LOGIC_PIT as (
    SELECT
        PO_HEADER_BK                                                 as                                       PO_HEADER_ID
      , PO_NUMBER
      , PO_LINE_NUMBER
      , TRANSACTION_ID
      , MATERIAL_DOCUMENT_NUMBER
      , MATERIAL_DOCUMENT_ITEM
      , RELEASE_NUMBER
      , SUPPLIER_BK
      , ITEM_BK
      , PLANT_BK
      , LEGAL_ENTITY_BK
      , PO_RECEIPT_DATE
      , TO_CHAR(PO_RECEIPT_DATE, 'YYYYMMDD')::INTEGER                as                          PO_RECEIPT_DATE__YYYYMMDD
      , PO_RECEIPT_QUANTITY
      , PO_RECEIPT_PRICE
      , PO_RECEIPT_VALUE_LOCAL
      , PO_RECEIPT_VALUE
      , PROMISED_DATE_LATEST__YYYYMMDD
      , PROMISED_DATE_EARLIEST__YYYYMMDD
      , NEED_BY_DATE_LATEST__YYYYMMDD
      , NEED_BY_DATE_EARLIEST__YYYYMMDD
      , ORIGINAL_PROMISED_DATE__YYYYMMDD
      , PO_HEADER_HK
      , SUPPLIER_HK
      , ITEM_HK
      , PLANT_HK
      , LEGAL_ENTITY_HK
      , PO_LINE_RECEIPT_IND_HK
      , BKCC
      , REC_SRC
    FROM SRC_PIT
)
---- RENAME LAYER ----

, RENAME_PIT as (
    SELECT
        PO_HEADER_ID
      , PO_NUMBER
      , PO_LINE_NUMBER
      , TRANSACTION_ID
      , MATERIAL_DOCUMENT_NUMBER
      , MATERIAL_DOCUMENT_ITEM
      , RELEASE_NUMBER
      , SUPPLIER_BK
      , ITEM_BK
      , PLANT_BK
      , LEGAL_ENTITY_BK
      , PO_RECEIPT_DATE
      , PO_RECEIPT_DATE__YYYYMMDD
      , PO_RECEIPT_QUANTITY
      , PO_RECEIPT_PRICE
      , PO_RECEIPT_VALUE_LOCAL
      , PO_RECEIPT_VALUE
      , PROMISED_DATE_LATEST__YYYYMMDD
      , PROMISED_DATE_EARLIEST__YYYYMMDD
      , NEED_BY_DATE_LATEST__YYYYMMDD
      , NEED_BY_DATE_EARLIEST__YYYYMMDD
      , ORIGINAL_PROMISED_DATE__YYYYMMDD
      , PO_HEADER_HK
      , SUPPLIER_HK
      , ITEM_HK
      , PLANT_HK
      , LEGAL_ENTITY_HK
      , PO_LINE_RECEIPT_IND_HK
      , BKCC
      , REC_SRC
    FROM LOGIC_PIT
)
---- FILTER LAYER ----

, FILTER_PIT as (
    SELECT *
    FROM RENAME_PIT
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_PIT
)

---- FINAL LAYER ----
SELECT
          PO_HEADER_ID
        , PO_NUMBER
        , PO_LINE_NUMBER
        , TRANSACTION_ID
        , MATERIAL_DOCUMENT_NUMBER
        , MATERIAL_DOCUMENT_ITEM
        , RELEASE_NUMBER
        , SUPPLIER_BK
        , ITEM_BK
        , PLANT_BK
        , LEGAL_ENTITY_BK
        , PO_RECEIPT_DATE__YYYYMMDD
        , PO_RECEIPT_QUANTITY
        , PO_RECEIPT_PRICE
        , PO_RECEIPT_VALUE_LOCAL
        , PO_RECEIPT_VALUE
        , PROMISED_DATE_LATEST__YYYYMMDD
        , PROMISED_DATE_EARLIEST__YYYYMMDD
        , NEED_BY_DATE_LATEST__YYYYMMDD
        , NEED_BY_DATE_EARLIEST__YYYYMMDD
        , ORIGINAL_PROMISED_DATE__YYYYMMDD
        , PO_HEADER_HK
        , SUPPLIER_HK
        , ITEM_HK
        , PLANT_HK
        , LEGAL_ENTITY_HK
        , PO_LINE_RECEIPT_IND_HK
        , BKCC
        , REC_SRC
FROM JOIN_RESULT
