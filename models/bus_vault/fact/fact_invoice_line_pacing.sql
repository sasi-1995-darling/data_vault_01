        , NET_VALUE
        , TAX_AMOUNT
        , INVOICED_DATE__YYYYMMDD
        , PLANT_BK
        , CUSTOMER_BK
        , DIVISION_BK
        , SALES_ORGANIZATION_BK
        , DISTRIBUTION_CHANNEL_BK
        , INVOICE_BK
        , INVOICE_LINE_BK
        , ITEM_BK
FROM JOIN_RESULT
