---- SRC LAYER ----
WITH
SRC_PDS            as ( SELECT ACCOUNT_ID, BKCC, CANCELED_AT, CANCELLATION_REASON, CANCEL_AT_PERIOD_END, CREATED_AT, CURRENT_PERIOD_END, CURRENT_PERIOD_START, DEVICE_ACCOUNT_BK, DEVICE_ACCOUNT_HK, ENDED_AT, FIVETRAN_DELETED, FIVETRAN_SYNCED, LOCATION_ID, PLAN_ID, REC_SRC, SOURCE_ID, STATUS, STRIPE_CUSTOMER_ID, STRIPE_SUBSCRIPTION_ID, UPDATED_AT FROM {{ ref('pit_stg_device_account_subscription') }} as SRC  )

/*
SRC_PDS            as ( SELECT * FROM BUS_VAULT.PIT_STG_DEVICE_ACCOUNT_SUBSCRIPTION )
*/
---- LOGIC LAYER ----

, LOGIC_PDS as (
    SELECT
        CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP )                  as                                       PIT_LOAD_DTS
      , DEVICE_ACCOUNT_HK
      , DEVICE_ACCOUNT_BK
      , BKCC
      , REC_SRC
      , ACCOUNT_ID
      , FIVETRAN_SYNCED
      , STRIPE_CUSTOMER_ID
      , UPDATED_AT
      , CANCEL_AT_PERIOD_END
      , CANCELED_AT
      , STRIPE_SUBSCRIPTION_ID
      , CURRENT_PERIOD_END
      , PLAN_ID
      , ENDED_AT
      , CURRENT_PERIOD_START
      , LOCATION_ID
      , STATUS
      , FIVETRAN_DELETED
      , CREATED_AT
      , SOURCE_ID
      , CANCELLATION_REASON
    FROM SRC_PDS
)
---- RENAME LAYER ----

, RENAME_PDS as (
    SELECT
        PIT_LOAD_DTS
      , DEVICE_ACCOUNT_HK
      , DEVICE_ACCOUNT_BK
      , BKCC
      , REC_SRC
      , ACCOUNT_ID
      , FIVETRAN_SYNCED
      , STRIPE_CUSTOMER_ID
      , UPDATED_AT
      , CANCEL_AT_PERIOD_END
      , CANCELED_AT
      , STRIPE_SUBSCRIPTION_ID
      , CURRENT_PERIOD_END
      , PLAN_ID
      , ENDED_AT
      , CURRENT_PERIOD_START
      , LOCATION_ID
      , STATUS
      , FIVETRAN_DELETED
      , CREATED_AT
      , SOURCE_ID
      , CANCELLATION_REASON
    FROM LOGIC_PDS
)
---- FILTER LAYER ----

, FILTER_PDS as (
    SELECT *
    FROM RENAME_PDS
)
---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT * FROM FILTER_PDS
)

---- FINAL LAYER ----
SELECT
              row_number() over(order by 1)                            as SEQ_ID
        , CURRENT_DATE                                                 as SNAPSHOTDATE
        , PIT_LOAD_DTS
        , DEVICE_ACCOUNT_HK
        , DEVICE_ACCOUNT_BK
        , BKCC
        , REC_SRC
        , ACCOUNT_ID
        , FIVETRAN_SYNCED
        , STRIPE_CUSTOMER_ID
        , UPDATED_AT
        , CANCEL_AT_PERIOD_END
        , CANCELED_AT
        , STRIPE_SUBSCRIPTION_ID
        , CURRENT_PERIOD_END
        , PLAN_ID
        , ENDED_AT
        , CURRENT_PERIOD_START
        , LOCATION_ID
        , STATUS
        , FIVETRAN_DELETED
        , CREATED_AT
        , SOURCE_ID
        , CANCELLATION_REASON
FROM JOIN_RESULT
