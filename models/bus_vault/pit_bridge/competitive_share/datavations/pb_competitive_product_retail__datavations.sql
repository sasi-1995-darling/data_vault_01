-- Purpose: PIT Bridge table for the competitive product + retailer dimension grain.
--          Grain: one row per COMPETITIVE_PRODUCT_HK + RETAILER_HK (latest LOAD_DTS per pair
--          from pb_pos_main_weekly__datavations), enriched with item descriptive attributes
--          from pb_item_details__datavations.
--          Intended upstream source for dim_competitive_product_retail.
-- Source:  pb_pos_main_weekly__datavations (product+retailer HKs+BKs, UPC, retailer attributes)
--          pb_item_details__datavations    (item descriptive attributes: name, brand, IDs)
-- Author:  Generated by GitHub Copilot

---- SRC LAYER ----
WITH
SRC_POS            as ( SELECT  SEQ_ID
                               , SNAPSHOT_DTS
                               , COMPETITIVE_PRODUCT_HK
                               , COMPETITIVE_PRODUCT_BK
                               , RETAILER_HK
                               , RETAILER_BK
                               , UPC
                               , RETAILER
                               , SECTOR
                               , BKCC
                               , REC_SRC
                               , LOAD_DTS
                        FROM {{ ref('pb_pos_main_weekly__datavations') }} as SRC
                        QUALIFY ROW_NUMBER() OVER(PARTITION BY COMPETITIVE_PRODUCT_HK, RETAILER_HK ORDER BY LOAD_DTS DESC) = 1 )

, SRC_ITEM         as ( SELECT  COMPETITIVE_PRODUCT_HK   as ITEM_COMPETITIVE_PRODUCT_HK
                               , ITEM_NAME
                               , ITEM_ID
                               , BRAND
                               , STORE_ITEM_ID
                               , ITEM_PSA_DELETE_IND
                        FROM {{ ref('pb_item_details__datavations') }} as SRC )

/*
SRC_POS            as ( SELECT * FROM bus_vault.PB_POS_MAIN_WEEKLY__DATAVATIONS )
SRC_ITEM           as ( SELECT * FROM bus_vault.PB_ITEM_DETAILS__DATAVATIONS )
*/

---- LOGIC LAYER ----

, LOGIC as (
    SELECT
        SEQ_ID
      , SNAPSHOT_DTS
      , COMPETITIVE_PRODUCT_HK
      , COMPETITIVE_PRODUCT_BK
      , RETAILER_HK
      , RETAILER_BK
      , UPC
      , RETAILER
      , SECTOR
      , BKCC
      , REC_SRC
      , LOAD_DTS
    FROM SRC_POS
)

---- JOIN LAYER ----

, JOIN_RESULT as (
    SELECT
        L.SEQ_ID
      , L.SNAPSHOT_DTS
      , L.COMPETITIVE_PRODUCT_HK
      , L.COMPETITIVE_PRODUCT_BK
      , L.RETAILER_HK
      , L.RETAILER_BK
      , L.UPC
      , L.RETAILER
      , L.SECTOR
      , I.ITEM_NAME
      , I.ITEM_ID
      , I.BRAND
      , I.STORE_ITEM_ID
      , I.ITEM_PSA_DELETE_IND
      , L.BKCC
      , L.REC_SRC
    FROM LOGIC L
    LEFT JOIN SRC_ITEM I ON L.COMPETITIVE_PRODUCT_HK = I.ITEM_COMPETITIVE_PRODUCT_HK  -- item descriptive attributes; LEFT to preserve products without item detail records
)

---- FINAL LAYER ----
SELECT
          SEQ_ID
        , SNAPSHOT_DTS
        , COMPETITIVE_PRODUCT_HK
        , COMPETITIVE_PRODUCT_BK
        , RETAILER_HK
        , RETAILER_BK
        , UPC
        , RETAILER
        , SECTOR
        , ITEM_NAME
        , ITEM_ID
        , BRAND
        , STORE_ITEM_ID
        , ITEM_PSA_DELETE_IND
        , BKCC
        , REC_SRC
FROM JOIN_RESULT
