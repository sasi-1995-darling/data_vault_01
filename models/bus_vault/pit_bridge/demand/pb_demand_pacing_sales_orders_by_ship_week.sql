---- SRC LAYER ----
WITH
SRC_PB_SALES_ORDER_LINE as (
    SELECT
          DISTRIBUTION_CHANNEL_HK
        , DISTRIBUTION_CHANNEL_BK
        , DIVISION_HK
        , DIVISION_BK
        , ITEM_HK
        , ITEM_BK
        , PLANT_HK
        , PLANT_BK
        , CUSTOMER_SOLDTO_HK
        , CUSTOMER_SOLDTO_BK
        , SALES_ORGANIZATION_HK
        , SALES_ORGANIZATION_BK
        , QUANTITY_ORDERED
        , REQUESTED_SHIP_DATE__YYYYMMDD
        , REC_SRC
        , BKCC
    FROM {{ ref('pb_sales_order_item') }}
)

, SRC_PIT_DATE_FBIN as (
    SELECT
          FBIN_CAL_WEEK_YYYYWW
        , DATE_BK
    FROM {{ ref('pit_date_fbin') }}
)

, SRC_PB_CUSTOMER_SALES_ATTRIBUTES as (
    SELECT
          APO_GROUP
        , CUSTOMER_HK
        , SALES_ORGANIZATION_HK
        , DISTRIBUTION_CHANNEL_HK
        , DIVISION_HK
        , BKCC
    FROM {{ ref('pb_customer_sales_attributes') }}
)

---- LOGIC LAYER ----

, LOGIC_PB_SALES_ORDER_LINE as (
    SELECT
          DISTRIBUTION_CHANNEL_HK
        , DISTRIBUTION_CHANNEL_BK
        , DIVISION_HK
        , DIVISION_BK
        , ITEM_HK
        , ITEM_BK
        , PLANT_HK
        , PLANT_BK
        , CUSTOMER_SOLDTO_HK
        , CUSTOMER_SOLDTO_BK
        , SALES_ORGANIZATION_HK
        , SALES_ORGANIZATION_BK
        , QUANTITY_ORDERED
        , REQUESTED_SHIP_DATE__YYYYMMDD
        , REC_SRC
        , BKCC
    FROM SRC_PB_SALES_ORDER_LINE
)

, LOGIC_PIT_DATE_FBIN as (
    SELECT
          FBIN_CAL_WEEK_YYYYWW
        , DATE_BK
    FROM SRC_PIT_DATE_FBIN
)

, LOGIC_PB_CUSTOMER_SALES_ATTRIBUTES as (
    SELECT
          APO_GROUP
        , CUSTOMER_HK as CUSTOMER_HK_DIM
        , SALES_ORGANIZATION_HK as SALES_ORGANIZATION_HK_DIM
        , DISTRIBUTION_CHANNEL_HK as DISTRIBUTION_CHANNEL_HK_DIM
        , DIVISION_HK as DIVISION_HK_DIM
        , BKCC as BKCC_DIM
    FROM SRC_PB_CUSTOMER_SALES_ATTRIBUTES
)

---- RENAME LAYER ----

, RENAME_PB_SALES_ORDER_LINE as (
    SELECT
          DISTRIBUTION_CHANNEL_HK
        , DISTRIBUTION_CHANNEL_BK
        , DIVISION_HK
        , DIVISION_BK
        , ITEM_HK
        , ITEM_BK
        , PLANT_HK
        , PLANT_BK
        , CUSTOMER_SOLDTO_HK
        , CUSTOMER_SOLDTO_BK
        , SALES_ORGANIZATION_HK
        , SALES_ORGANIZATION_BK
        , QUANTITY_ORDERED
        , REQUESTED_SHIP_DATE__YYYYMMDD
        , REC_SRC
        , BKCC
    FROM LOGIC_PB_SALES_ORDER_LINE
)

, RENAME_PIT_DATE_FBIN as (
    SELECT
          FBIN_CAL_WEEK_YYYYWW
        , DATE_BK
    FROM LOGIC_PIT_DATE_FBIN
)

, RENAME_PB_CUSTOMER_SALES_ATTRIBUTES as (
    SELECT
          APO_GROUP
        , CUSTOMER_HK_DIM
        , SALES_ORGANIZATION_HK_DIM
        , DISTRIBUTION_CHANNEL_HK_DIM
        , DIVISION_HK_DIM
        , BKCC_DIM
    FROM LOGIC_PB_CUSTOMER_SALES_ATTRIBUTES
)

---- FILTER LAYER ----

, FILTER_PB_SALES_ORDER_LINE as (
    SELECT *
    FROM RENAME_PB_SALES_ORDER_LINE
)

, FILTER_PIT_DATE_FBIN as (
    SELECT *
    FROM RENAME_PIT_DATE_FBIN
)

, FILTER_PB_CUSTOMER_SALES_ATTRIBUTES as (
    SELECT *
    FROM RENAME_PB_CUSTOMER_SALES_ATTRIBUTES
)

---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT *
    FROM FILTER_PB_SALES_ORDER_LINE as a
    JOIN FILTER_PIT_DATE_FBIN as c
    ON a.REQUESTED_SHIP_DATE__YYYYMMDD = c.DATE_BK
    LEFT JOIN FILTER_PB_CUSTOMER_SALES_ATTRIBUTES as e
       ON e.CUSTOMER_HK_DIM = a.CUSTOMER_SOLDTO_HK
      AND e.SALES_ORGANIZATION_HK_DIM = a.SALES_ORGANIZATION_HK
      AND e.DISTRIBUTION_CHANNEL_HK_DIM = a.DISTRIBUTION_CHANNEL_HK
      AND e.DIVISION_HK_DIM = a.DIVISION_HK
      AND e.BKCC_DIM = a.BKCC
)

---- FINAL LAYER ----
SELECT
          DISTRIBUTION_CHANNEL_HK
        , DISTRIBUTION_CHANNEL_BK
        , DIVISION_HK
        , DIVISION_BK
        , ITEM_HK
        , ITEM_BK
        , PLANT_HK
        , PLANT_BK
        , CUSTOMER_SOLDTO_HK
        , CUSTOMER_SOLDTO_BK
        , SALES_ORGANIZATION_HK
        , SALES_ORGANIZATION_BK
        , APO_GROUP as APO_CUSTOMER_GROUP
        , FBIN_CAL_WEEK_YYYYWW AS REQUESTED_SHIP_WEEK__YYYYWW
        , REC_SRC
        , BKCC
        , SUM(QUANTITY_ORDERED) as WEEKLY_ORDERED_QUANTITY
        , 'PB_DEMAND_PACING_SALES_ORDERS_BY_SHIP_WEEK' as PB_REC_SRC
        , SEQ8()                                                       as SEQ_ID
        , CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP )                  as PB_LOAD_DTS

FROM JOIN_RESULT
GROUP BY 
          DISTRIBUTION_CHANNEL_HK 
        , DISTRIBUTION_CHANNEL_BK
        , DIVISION_HK
        , DIVISION_BK
        , ITEM_HK
        , ITEM_BK
        , PLANT_HK
        , PLANT_BK
        , CUSTOMER_SOLDTO_HK
        , CUSTOMER_SOLDTO_BK
        , SALES_ORGANIZATION_HK
        , SALES_ORGANIZATION_BK
        , APO_GROUP
        , FBIN_CAL_WEEK_YYYYWW
        , REC_SRC
        , BKCC