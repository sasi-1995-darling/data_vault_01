                        DIVISION_HK, ITEM_HK, LOAD_DTS, ORDER_HEADER_HK, ORDER_LINE_HK, PLANT_HK, REC_SRC, SALES_ORGANIZATION_HK, SO_ITEM_LHK FROM {{ ref('lnk_sales_order_line') }} as SRC  ),
SRC_H_CUSTOMER           as ( SELECT BKCC, REC_SRC, CUSTOMER_HK, CUSTOMER_BK FROM {{ ref('hub_customer_v1') }} as SRC  ),
SRC_H_DISTRIBUTION           as ( SELECT DISTRIBUTION_CHANNEL_HK, DISTRIBUTION_CHANNEL_BK FROM {{ ref('hub_distribution_channel') }} as SRC  ),
SRC_H_DIVISION          as ( SELECT DIVISION_HK, DIVISION_BK FROM {{ ref('hub_division') }} as SRC  ),
SRC_H_ITEM           as ( SELECT ITEM_HK, ITEM_BK FROM {{ ref('hub_item_v1') }} as SRC  ),
SRC_H_ORDER_HEADER           as ( SELECT ORDER_HEADER_HK, ORDER_HEADER_BK FROM {{ ref('hub_order_header') }} as SRC  ),
SRC_H_ORDER_LINE           as ( SELECT ORDER_LINE_HK, ORDER_LINE_BK FROM {{ ref('hub_order_line') }} as SRC  ),
SRC_H_PLANT           as ( SELECT PLANT_HK, PLANT_BK FROM {{ ref('hub_plant_v1') }} as SRC  ),
SRC_H_SALES_ORGANIZATION           as ( SELECT SALES_ORGANIZATION_HK, SALES_ORGANIZATION_BK FROM {{ ref('hub_sales_organization') }} as SRC  ),
SRC_LS             as ( SELECT PSA_DELETE_IND, ORDER_LINE_HK, VRKME, NETWR, KWMENG, MWSBP, ABGRU, ERDAT, MATKL
                        FROM {{ ref('sat_order_line__winn_sap') }} as SRC 
                        QUALIFY 1= ROW_NUMBER() OVER(PARTITION BY ORDER_LINE_HK ORDER BY LOAD_DTS DESC) ),
SRC_LS_HEADER      as ( SELECT ORDER_HEADER_HK, AUART, AUDAT, ZZRSD
                        FROM {{ ref('sat_order_header__winn_sap') }} as SRC 
                        QUALIFY 1= ROW_NUMBER() OVER(PARTITION BY ORDER_HEADER_HK ORDER BY LOAD_DTS DESC) )


