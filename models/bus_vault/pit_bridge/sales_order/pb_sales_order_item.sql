---- JOIN LAYER ----
, JOIN_RESULT as (
    SELECT
        FILTER_L.PB_REC_SRC
      , FILTER_L.L_CUSTOMER_BILLTO_HK
      , FILTER_L.L_CUSTOMER_INSURANCEPARTNER_HK
      , FILTER_L.L_CUSTOMER_PAYER_HK
      , FILTER_L.L_CUSTOMER_SHIPTO_HK
      , FILTER_L.L_CUSTOMER_SOLDTO_HK
      , FILTER_L.L_DISTRIBUTION_CHANNEL_HK
      , FILTER_L.L_DIVISION_HK
      , FILTER_L.L_ITEM_HK
      , FILTER_L.LOAD_DTS
      , FILTER_L.L_ORDER_HEADER_HK
      , FILTER_L.L_ORDER_LINE_HK
      , FILTER_L.L_PLANT_HK
      , FILTER_L.REC_SRC
      , FILTER_L.L_SALES_ORGANIZATION_HK
      , FILTER_L.SO_ITEM_LHK
      
      -- Hub Customer (BillTo)
      , H_CUSTOMER_BILLTO.CUSTOMER_HK as CUSTOMER_BILLTO_HK
      , H_CUSTOMER_BILLTO.CUSTOMER_BK as CUSTOMER_BILLTO_BK
      , H_CUSTOMER_BILLTO.BKCC
      
      -- Hub Customer (Payer)
      , H_CUSTOMER_PAYER.CUSTOMER_HK as CUSTOMER_PAYER_HK
      , H_CUSTOMER_PAYER.CUSTOMER_BK as CUSTOMER_PAYER_BK
      
      -- Hub Customer (ShipTo)
      , H_CUSTOMER_SHIPTO.CUSTOMER_HK as CUSTOMER_SHIPTO_HK
      , H_CUSTOMER_SHIPTO.CUSTOMER_BK as CUSTOMER_SHIPTO_BK
      
      -- Hub Customer (SoldTo)
      , H_CUSTOMER_SOLDTO.CUSTOMER_HK as CUSTOMER_SOLDTO_HK
      , H_CUSTOMER_SOLDTO.CUSTOMER_BK as CUSTOMER_SOLDTO_BK
      
      -- Hub Distribution
      , H_DISTRIBUTION.DISTRIBUTION_CHANNEL_HK
      , H_DISTRIBUTION.DISTRIBUTION_CHANNEL_BK
      
      -- Hub Division
      , H_DIVISION.DIVISION_HK
      , H_DIVISION.DIVISION_BK
      
      -- Hub Item
      , H_ITEM.ITEM_HK
      , H_ITEM.ITEM_BK
      
      -- Hub Order Header
      , H_ORDER_HEADER.ORDER_HEADER_HK
      , H_ORDER_HEADER.ORDER_HEADER_BK
      
      -- Hub Order Line
      , H_ORDER_LINE.ORDER_LINE_HK
      , H_ORDER_LINE.ORDER_LINE_BK
      
      -- Hub Plant
      , H_PLANT.PLANT_HK
      , H_PLANT.PLANT_BK
      
      -- Hub Sales Organization
      , H_SALES_ORG.SALES_ORGANIZATION_HK
      , H_SALES_ORG.SALES_ORGANIZATION_BK

      -- Satellite Line Attributes
      , FILTER_LS.PSA_DELETE_IND
      , FILTER_LS.SOLD_UNIT_OF_MEASURE
      , FILTER_LS.NET_VALUE_AMOUNT
      , FILTER_LS.TAX_AMOUNT
      , FILTER_LS.CANCELLED_REASON
      , FILTER_LS.CREATION_DATE__YYYYMMDD
      , FILTER_LS.MATERIAL_GROUP
      , FILTER_LS.QUANTITY_ORDERED

      -- Satellite Header Attributes
      , FILTER_LS_HEADER.ORDER_TYPE
      , FILTER_LS_HEADER.ORDER_DATE__YYYYMMDD
      , FILTER_LS_HEADER.REQUESTED_SHIP_DATE__YYYYMMDD
      
    FROM FILTER_L
    
    INNER JOIN FILTER_H_CUSTOMER as H_CUSTOMER_BILLTO
        ON FILTER_L.L_CUSTOMER_BILLTO_HK = H_CUSTOMER_BILLTO.CUSTOMER_HK
        
    INNER JOIN FILTER_H_CUSTOMER as H_CUSTOMER_PAYER
        ON FILTER_L.L_CUSTOMER_PAYER_HK = H_CUSTOMER_PAYER.CUSTOMER_HK
        
    INNER JOIN FILTER_H_CUSTOMER as H_CUSTOMER_SHIPTO
        ON FILTER_L.L_CUSTOMER_SHIPTO_HK = H_CUSTOMER_SHIPTO.CUSTOMER_HK
        
    INNER JOIN FILTER_H_CUSTOMER as H_CUSTOMER_SOLDTO
        ON FILTER_L.L_CUSTOMER_SOLDTO_HK = H_CUSTOMER_SOLDTO.CUSTOMER_HK
        
    INNER JOIN FILTER_H_DISTRIBUTION as H_DISTRIBUTION
        ON FILTER_L.L_DISTRIBUTION_CHANNEL_HK = H_DISTRIBUTION.DISTRIBUTION_CHANNEL_HK
        
    INNER JOIN FILTER_H_DIVISION as H_DIVISION
        ON FILTER_L.L_DIVISION_HK = H_DIVISION.DIVISION_HK
        
    INNER JOIN FILTER_H_ITEM as H_ITEM
        ON FILTER_L.L_ITEM_HK = H_ITEM.ITEM_HK
        
    INNER JOIN FILTER_H_ORDER_HEADER as H_ORDER_HEADER
        ON FILTER_L.L_ORDER_HEADER_HK = H_ORDER_HEADER.ORDER_HEADER_HK
        
    INNER JOIN FILTER_H_ORDER_LINE as H_ORDER_LINE
        ON FILTER_L.L_ORDER_LINE_HK = H_ORDER_LINE.ORDER_LINE_HK
        
    INNER JOIN FILTER_H_PLANT as H_PLANT
        ON FILTER_L.L_PLANT_HK = H_PLANT.PLANT_HK
        
    INNER JOIN FILTER_H_SALES_ORGANIZATION as H_SALES_ORG
        ON FILTER_L.L_SALES_ORGANIZATION_HK = H_SALES_ORG.SALES_ORGANIZATION_HK
        
    INNER JOIN FILTER_LS
        ON FILTER_L.L_ORDER_LINE_HK = FILTER_LS.ORDER_LINE_HK
        
    INNER JOIN FILTER_LS_HEADER
        ON FILTER_L.L_ORDER_HEADER_HK = FILTER_LS_HEADER.ORDER_HEADER_HK
)

---- FINAL LAYER ----
