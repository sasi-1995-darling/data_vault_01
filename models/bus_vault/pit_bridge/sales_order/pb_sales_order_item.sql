---- LOGIC LAYER ----

, LOGIC_L as (
    SELECT
        'PB_SALES_ORDER_ITEM'                                                     as PB_REC_SRC
      , CUSTOMER_BILLTO_HK                                                        as L_CUSTOMER_BILLTO_HK
      , CUSTOMER_INSURANCEPARTNER_HK                                              as L_CUSTOMER_INSURANCEPARTNER_HK
      , CUSTOMER_PAYER_HK                                                         as L_CUSTOMER_PAYER_HK
      , CUSTOMER_SHIPTO_HK                                                        as L_CUSTOMER_SHIPTO_HK
      , CUSTOMER_SOLDTO_HK                                                        as L_CUSTOMER_SOLDTO_HK
      , DISTRIBUTION_CHANNEL_HK                                                   as L_DISTRIBUTION_CHANNEL_HK
      , DIVISION_HK                                                               as L_DIVISION_HK
      , ITEM_HK                                                                   as L_ITEM_HK
      , LOAD_DTS
      , ORDER_HEADER_HK                                                           as L_ORDER_HEADER_HK
      , ORDER_LINE_HK                                                             as L_ORDER_LINE_HK
      , PLANT_HK                                                                  as L_PLANT_HK
      , REC_SRC
      , SALES_ORGANIZATION_HK                                                     as L_SALES_ORGANIZATION_HK
      , SO_ITEM_LHK
    FROM SRC_L
)

