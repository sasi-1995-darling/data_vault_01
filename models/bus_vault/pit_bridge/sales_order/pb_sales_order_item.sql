        , CUSTOMER_PAYER_HK
        , CUSTOMER_PAYER_BK
        , CUSTOMER_SHIPTO_HK
        , CUSTOMER_SHIPTO_BK
        , CUSTOMER_SOLDTO_HK
        , CUSTOMER_SOLDTO_BK
        , DISTRIBUTION_CHANNEL_HK
        , DISTRIBUTION_CHANNEL_BK
        , DIVISION_HK
        , DIVISION_BK
        , ITEM_HK
        , ITEM_BK
        , ORDER_HEADER_HK
        , ORDER_HEADER_BK
        , ORDER_LINE_HK
        , ORDER_LINE_BK
        , PLANT_HK
        , PLANT_BK
        , SALES_ORGANIZATION_HK
        , SALES_ORGANIZATION_BK
        , ORDER_TYPE
        , QUANTITY_ORDERED
        , SOLD_UNIT_OF_MEASURE
        , NET_VALUE_AMOUNT
        , TAX_AMOUNT
        , CANCELLED_REASON
        , ORDER_DATE__YYYYMMDD
        , CREATION_DATE__YYYYMMDD
        , REQUESTED_SHIP_DATE__YYYYMMDD
        , MATERIAL_GROUP 
FROM JOIN_RESULT