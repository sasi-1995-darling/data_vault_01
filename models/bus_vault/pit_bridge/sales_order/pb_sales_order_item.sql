        DIVISION_BK
      , DIVISION_HK
    FROM SRC_H_DIVISION
) 

, LOGIC_H_ITEM as (
    SELECT
        ITEM_BK
      , ITEM_HK
    FROM SRC_H_ITEM
) 

, LOGIC_H_ORDER_HEADER as (
    SELECT
        ORDER_HEADER_BK
      , ORDER_HEADER_HK
    FROM SRC_H_ORDER_HEADER
) 


, LOGIC_H_ORDER_LINE as (
    SELECT
        ORDER_LINE_BK
      , ORDER_LINE_HK
    FROM SRC_H_ORDER_LINE
)


, LOGIC_H_PLANT as (
    SELECT
        PLANT_BK
      , PLANT_HK
    FROM SRC_H_PLANT
