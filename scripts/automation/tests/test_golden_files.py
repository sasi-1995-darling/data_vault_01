"""Golden-file regression tests for code generation.

Ensures that main.py --yaml-config produces identical SQL and YAML output
for known-good YAML config inputs. Any diff = regression in code generation.

How to update golden files after an intentional change:
    cd scripts/automation
    ../../.venv/bin/python3 src/main.py --yaml-config configs/integration_test/<config>.yml --silent
    cp models/int_staging_views/<model>.sql tests/golden_files/<model>.sql.golden
    cp models/int_staging_views/<model>.yml tests/golden_files/<model>.yml.golden
"""
import difflib
import subprocess
import sys
from pathlib import Path

import pytest

# Resolve paths
TESTS_DIR = Path(__file__).resolve().parent
AUTOMATION_DIR = TESTS_DIR.parent
GOLDEN_DIR = TESTS_DIR / "golden_files"
REPO_ROOT = AUTOMATION_DIR.parent.parent
PYTHON = sys.executable

# Each fixture: (yaml_config_path, model_name)
FIXTURES = [
    pytest.param(
        "configs/integration_test/retailers__appbot.yml",
        "v_psa_stg_retailers__appbot",
        id="retailers-appbot-simple",
    ),
    pytest.param(
        "configs/integration_test/dispute__stripe_flosense.yml",
        "v_psa_stg_dispute__stripe_flosense",
        id="dispute-stripe-38col-hashdiff",
    ),
    pytest.param(
        "configs/integration_test/payment_terms_lines__fib_ocf.yml",
        "v_psa_stg_payment_terms_lines__fib_ocf",
        id="payment-terms-oracle-45col",
    ),
    pytest.param(
        "configs/integration_test/po_item_multi_table__lrsn_psft.yml",
        "v_psa_stg_po_item_mt__lrsn_psft",
        id="po-item-multi-table-secondary-join",
    ),
]

# Generated output directory (cleaned up after tests to avoid dirty worktree)
GENERATED_DIR = AUTOMATION_DIR / "models" / "int_staging_views"


@pytest.fixture(autouse=True)
def _cleanup_generated_files():
    """Remove generated output files after each test to keep worktree clean."""
    yield
    # Clean up .sql and .yml files generated by _run_codegen
    if GENERATED_DIR.exists():
        for ext in ("*.sql", "*.yml"):
            for f in GENERATED_DIR.glob(ext):
                f.unlink(missing_ok=True)
        # Remove directory if empty
        try:
            GENERATED_DIR.rmdir()
        except OSError:
            pass  # Not empty (has subdirs) — that's fine


def _run_codegen(yaml_config: str) -> None:
    """Run main.py --yaml-config to generate SQL + YAML files."""
    result = subprocess.run(
        [PYTHON, str(AUTOMATION_DIR / "src" / "main.py"),
         "--yaml-config", str(AUTOMATION_DIR / yaml_config),
         "--silent"],
        capture_output=True,
        text=True,
        cwd=str(AUTOMATION_DIR),
        timeout=30,
    )
    if result.returncode != 0:
        pytest.fail(
            f"Code generation failed (rc={result.returncode}):\n"
            f"STDOUT: {result.stdout}\nSTDERR: {result.stderr}"
        )


def _diff_files(actual_path: Path, golden_path: Path, label: str) -> None:
    """Compare actual output against golden reference using unified diff."""
    actual = actual_path.read_text(encoding="utf-8")
    golden = golden_path.read_text(encoding="utf-8")

    if actual == golden:
        return

    diff = list(difflib.unified_diff(
        golden.splitlines(keepends=True),
        actual.splitlines(keepends=True),
        fromfile=f"golden/{golden_path.name}",
        tofile=f"actual/{actual_path.name}",
        n=3,
    ))
    diff_text = "".join(diff)
    pytest.fail(
        f"Golden-file mismatch for {label}:\n\n{diff_text}\n\n"
        f"If this change is intentional, update the golden file:\n"
        f"  cp {actual_path} {golden_path}"
    )


class TestGoldenFileSQL:
    """Generated SQL must match golden reference exactly."""

    @pytest.mark.parametrize("yaml_config,model_name", FIXTURES)
    def test_sql_matches_golden(self, yaml_config, model_name):
        _run_codegen(yaml_config)

        actual = AUTOMATION_DIR / "models" / "int_staging_views" / f"{model_name}.sql"
        golden = GOLDEN_DIR / f"{model_name}.sql.golden"

        assert actual.exists(), f"Generated SQL not found: {actual}"
        assert golden.exists(), f"Golden SQL not found: {golden}"

        _diff_files(actual, golden, f"{model_name}.sql")


class TestGoldenFileYAML:
    """Generated YAML schema must match golden reference exactly."""

    @pytest.mark.parametrize("yaml_config,model_name", FIXTURES)
    def test_yml_matches_golden(self, yaml_config, model_name):
        _run_codegen(yaml_config)

        actual = AUTOMATION_DIR / "models" / "int_staging_views" / f"{model_name}.yml"
        golden = GOLDEN_DIR / f"{model_name}.yml.golden"

        assert actual.exists(), f"Generated YAML not found: {actual}"
        assert golden.exists(), f"Golden YAML not found: {golden}"

        _diff_files(actual, golden, f"{model_name}.yml")
