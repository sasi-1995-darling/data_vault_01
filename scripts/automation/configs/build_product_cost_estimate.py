# ── Helpers ───────────────────────────────────────────────────────────────────
def ghost(dtype):
    return 'value_number' if dtype == 'NUMBER' else 'value_text'


def sat_col(alias, src, dtype, staging=None, comment='', hk=False, pk=None, rel=None, manual=None):
    staging = staging or src
    entry = {
        'source_table': alias,
        'source_column': src,
        'datatype': dtype,
        'staging_column_name': staging,
        'staging_datatype': dtype,
        'mapping_notes': comment,
    }
    if hk:
        entry['ghost_record'] = 'hash'
        if manual:
            entry['manual_logic'] = manual
        if pk:
            entry['pk'] = pk
        if rel:
            entry['relationship'] = rel
    else:
        entry['ghost_record'] = ghost(dtype)
        entry['hashdiff'] = 'yes'
    return entry


def pb_col(alias, src, dtype, staging=None, comment='', pk=None, rel=None, manual=None):
    staging = staging or src
    entry = {
        'source_table': alias,
        'source_column': src,
        'datatype': dtype,
        'staging_column_name': staging,
        'staging_datatype': dtype,
    }
    if comment:
        entry['mapping_notes'] = comment
    if pk:
        entry['pk'] = pk
    if rel:
        entry['relationship'] = rel
    if manual:
        entry['manual_logic'] = manual
    return entry


