import yaml
import logging
from tests import get_model_tests, get_column_tests

logger = logging.getLogger(__name__)

def make_yml(table_name, tables, columns):
    logger.debug('FUNCTION: make_yml')
    logger.debug(f'==== Building YAML for {table_name} ...')

    model_tests = []
    column_tests = {}

    # Get the derived name from the first table in the tables dictionary
    first_table_entry = next(iter(tables.values()))[0]
    derived_name = first_table_entry['DERIVED_NAME']
    output_name = derived_name.replace(' ', '_').lower()

    is_stg = table_name.startswith('STG_') or 'v_psa_stg' in output_name
    is_raw_vault = table_name.startswith(('LNK_', 'HUB_', 'SAT_', 'LSAT_', 'MSAT_', 'ESAT_', 'LMSAT_', 'LINK_', 'TLINK_'))
    is_hub = table_name.startswith('HUB_')
    is_lnk = table_name.startswith(('LNK_', 'LINK_', 'TLINK_'))
    is_sat = table_name.startswith(('SAT_', 'LSAT_', 'MSAT_', 'LMSAT_', 'ESAT_'))
    is_msat = table_name.startswith(('MSAT_', 'LMSAT_'))
    is_link_sat = table_name.startswith(('LSAT_', 'LMSAT_'))

    # Layer-specific severity: STG, HUB, LNK, SAT → warn
    test_severity = 'warn' if (is_stg or is_hub or is_lnk or is_sat) else 'error'

    # Collect all row-level tests and find BK/grain info
    bk_col = None
    composite_grain = None
    has_composite_test = False

    for idx, (key, row) in enumerate(columns.items()):
        col_name = row.get('STAGING LAYER COLUMN NAME', '')
        # Use UPPERCASE keys (matching both XLSX process_columns and yaml_reader output)
        unique = (row.get('UNIQUE') or '').strip()
        not_null = (row.get('NOT NULL') or '').strip()

        # Detect BK column: unique=yes + not_null=yes (YAML path default)
        if unique.lower() in ('yes', 'y') and not_null.lower() in ('yes', 'y'):
            bk_col = col_name

        # Detect COMPOSITE grain from XLSX Unique column (e.g., "COMPOSITE: BK, SEQ, LOAD_DTS")
        if 'COMPOSITE:' in unique.upper() and not_null.lower() in ('yes', 'y'):
            bk_col = col_name
            grain_str = unique.split(':', 1)[1].strip()
            composite_grain = [c.strip() for c in grain_str.split(',')]
            logger.info(f"Detected COMPOSITE grain: {composite_grain}")

        # Generate row-level model/column tests
        if col_name:
            row_model_tests = get_model_tests(row, table_name, severity=test_severity)
            # Check if get_model_tests generated a unique_combination_of_columns test
            for t in row_model_tests:
                if isinstance(t, dict) and 'dbt_utils.unique_combination_of_columns' in t:
                    has_composite_test = True
            model_tests.extend(row_model_tests)
            column_tests[col_name] = get_column_tests(row, table_name, severity=test_severity)

    # For STG models, add grain test if not already generated by get_model_tests
    logger.debug(f"STG check - table_name={table_name}, bk_col={bk_col}, composite_grain={composite_grain}, has_composite_test={has_composite_test}")
    if is_stg and bk_col and not has_composite_test:
        # Use COMPOSITE grain if available, otherwise default to [BK, LOAD_DTS]
        grain_columns = composite_grain if composite_grain else [bk_col, 'LOAD_DTS']
        logger.debug(f"Adding grain test with columns={grain_columns}")
        model_tests.append({
            'dbt_utils.unique_combination_of_columns': {
                'arguments': {
                    'combination_of_columns': grain_columns
                },
                'config': {
                    'severity': test_severity
                }
            }
        })

    # Add test for Hubs, Links, Sats, and LSats to check for more than 3 rows
    if is_raw_vault:
        model_tests.append({
            'dbt_expectations.expect_table_row_count_to_be_between': {
                'name': f'rowcount_{output_name}',
                'arguments': {
                    'min_value': 4
                },
                'config': {
                    'severity': test_severity
                }
            }
        })

    # Add dbt_constraints.primary_key for hub models.
    # If get_model_tests already detected a PK column (via "PK:" format),
    # it will have added the test above. This is a fallback for hub models
    # where the PK didn't have the "PK:" prefix format.
    if is_hub:
        has_pk_test = any(
            isinstance(t, dict) and 'dbt_constraints.primary_key' in t
            for t in model_tests
        )
        if not has_pk_test:
            # Find the HK column (PK for hubs)
            hk_col = None
            for row in columns.values():
                staging_name = (row.get('STAGING LAYER COLUMN NAME') or '').upper()
                if staging_name.endswith('_HK'):
                    hk_col = staging_name
                    break
            if hk_col:
                model_tests.append({
                    'dbt_constraints.primary_key': {
                        'name': f'pk_{output_name}',
                        'arguments': {
                            'column_names': [hk_col]
                        },
                        'config': {
                            'severity': test_severity
                        }
                    }
                })

    # Add dbt_constraints.primary_key fallback for link models.
    if is_lnk:
        has_pk_test = any(
            isinstance(t, dict) and 'dbt_constraints.primary_key' in t
            for t in model_tests
        )
        if not has_pk_test:
            # Find the LHK column (PK for links: starts with LNK_)
            lhk_col = None
            for row in columns.values():
                staging_name = (row.get('STAGING LAYER COLUMN NAME') or '').upper()
                if staging_name.startswith('LNK_') and staging_name.endswith('_HK'):
                    lhk_col = staging_name
                    break
            if lhk_col:
                model_tests.append({
                    'dbt_constraints.primary_key': {
                        'name': f'pk_{output_name}',
                        'arguments': {
                            'column_names': [lhk_col]
                        },
                        'config': {
                            'severity': test_severity
                        }
                    }
                })

    # Add dbt_constraints.primary_key for SAT models.
    # SAT PK = (PARENT_HK, LOAD_DTS) — or (PARENT_HK, MULTI_ACTIVE_KEY, LOAD_DTS) for MSAT.
    if is_sat:
        has_pk_test = any(
            isinstance(t, dict) and 'dbt_constraints.primary_key' in t
            for t in model_tests
        )
        if not has_pk_test:
            # Find parent HK column (first _HK or _LHK column)
            parent_hk_col = None
            for row in columns.values():
                staging_name = (row.get('STAGING LAYER COLUMN NAME') or '').upper()
                pk_val = (row.get('PK') or '').upper()
                if pk_val.startswith('PK:') and staging_name.endswith(('_HK', '_LHK')):
                    parent_hk_col = staging_name
                    break
            if not parent_hk_col:
                # Fallback: find first _HK or _LHK column
                for row in columns.values():
                    staging_name = (row.get('STAGING LAYER COLUMN NAME') or '').upper()
                    if staging_name.endswith(('_HK', '_LHK')):
                        parent_hk_col = staging_name
                        break

            if parent_hk_col:
                # Parse PK columns from the PK: field (e.g., "PK: HK, MA_KEY, LOAD_DTS")
                pk_cols = [parent_hk_col]
                for row in columns.values():
                    pk_val = (row.get('PK') or '').strip()
                    if pk_val.upper().startswith('PK:'):
                        pk_parts = pk_val.split(':', 1)[1].strip()
                        pk_cols = [p.strip().upper() for p in pk_parts.split(',')]
                        break
                model_tests.append({
                    'dbt_constraints.primary_key': {
                        'name': f'pk_{output_name}',
                        'arguments': {
                            'column_names': pk_cols
                        },
                        'config': {
                            'severity': test_severity
                        }
                    }
                })

    # Ensure all model-level tests have explicit 'name:' to prevent
    # dbt partial-parse duplicate registration (dbt Cloud CI bug).
    # Track assigned names to avoid collisions when multiple tests of same type exist.
    # Pre-populate with names already set by explicit blocks above.
    assigned_names = set()
    for test_entry in model_tests:
        if isinstance(test_entry, dict):
            for test_props in test_entry.values():
                if isinstance(test_props, dict) and 'name' in test_props:
                    assigned_names.add(test_props['name'])
    for test_entry in model_tests:
        if isinstance(test_entry, dict):
            for test_key, test_props in test_entry.items():
                if isinstance(test_props, dict) and 'name' not in test_props:
                    # Derive name from test type + model name.
                    # Well-known test types get short, conventional names;
                    # everything else (dbt_utils.equality, equal_rowcount,
                    # expression_is_true, etc.) falls through to a generic
                    # "<short_test_key>_<output_name>" so EVERY model-level
                    # test gets a stable, dedupable name. Skipping any type
                    # here would re-introduce the partial-parse duplicate
                    # registration bug that #1770 hot-fixed.
                    if 'primary_key' in test_key:
                        base_name = f'pk_{output_name}'
                    elif 'expect_table_row_count' in test_key:
                        base_name = f'rowcount_{output_name}'
                    elif 'unique_combination_of_columns' in test_key:
                        base_name = f'grain_{output_name}'
                    else:
                        # Generic fallback: take the last dotted segment of
                        # the test key (e.g. 'dbt_utils.equality' -> 'equality'),
                        # lowercase, alnum/underscore-only.
                        short = test_key.split('.')[-1].lower()
                        short = ''.join(
                            ch if (ch.isalnum() or ch == '_') else '_'
                            for ch in short
                        ) or 'test'
                        base_name = f'{short}_{output_name}'
                    # Deduplicate: append counter if name already assigned
                    name_val = base_name
                    counter = 2
                    while name_val in assigned_names:
                        name_val = f'{base_name}_{counter}'
                        counter += 1
                    assigned_names.add(name_val)
                    # Insert name as first key (Python 3.7+ preserves order)
                    new_props = {'name': name_val}
                    new_props.update(test_props)
                    test_entry[test_key] = new_props

    schema_dict = {
        'version': 2,
        'models': [
            {
                'name': output_name,  # Use the derived name here
                'data_tests': model_tests,  # Updated from 'tests' to 'data_tests'
                'columns': []
            }
        ]
    }

    # config.enabled removed — not needed for sandbox builds

    # For hub models, add tags config
    if is_hub:
        schema_dict['models'][0]['config'] = {
            'tags': ['hub']
        }

    # For lnk models, add tags config
    if is_lnk:
        schema_dict['models'][0]['config'] = {
            'tags': ['lnk']
        }

    # For SAT models, add tags config
    if is_sat:
        # Determine SAT variant tag
        if table_name.startswith('LMSAT_'):
            sat_tag = 'lmsat'
        elif table_name.startswith('MSAT_'):
            sat_tag = 'msat'
        elif table_name.startswith('LSAT_'):
            sat_tag = 'lsat'
        else:
            sat_tag = 'sat'

        sat_config = {'tags': [sat_tag]}
        schema_dict['models'][0]['config'] = sat_config

    for col_name, tests in column_tests.items():
        if tests:
            # Remove dbt_utils.relationships_where tests
            tests = [test for test in tests if not _is_relationships_where_test(test)]
            if tests:
                column_entry = {
                    'name': col_name,
                    'data_tests': tests  # Updated from 'tests' to 'data_tests'
                }
                schema_dict['models'][0]['columns'].append(column_entry)

    logger.debug(f"Generated YAML for {output_name}:")
    logger.debug(yaml.dump(schema_dict, sort_keys=False))

    return schema_dict


def _is_relationships_where_test(test):
    """
    Helper function to check if a test is a dbt_utils.relationships_where test.
    Handles both dict and string formats.
    """
    if isinstance(test, dict):
        return any('dbt_utils.relationships_where' in str(key) for key in test.keys())
    elif isinstance(test, str):
        return 'dbt_utils.relationships_where' in test
    return False